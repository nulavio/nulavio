"""Nulavio profiles: isolated engine profiles plus Nulavio settings.

Layout of ``$XDG_DATA_HOME/nulavio/profiles/<name>/`` (all 0700/0600):

    prefs.js, user.js, extensions/ ...   engine-owned profile files
    nulavio/settings.json                Nulavio choices for this profile
    nulavio/startpage/                   generated local start page

Preference strategy (see browser/config/prefs/baseline.js):
* ``seed`` prefs are appended to prefs.js only while the profile is *not*
  running; afterwards they are ordinary user choices. A seeded value that
  nobody changed follows the baseline when the baseline's value changes
  (``seed_states``); a value the person changed is kept.
* ``enforce`` prefs are rendered into user.js on every launch.
"""

from __future__ import annotations

import contextlib
import datetime as _dt
import fcntl
import hashlib
import html
import json
import os
import re
import shutil
import time
from dataclasses import dataclass
from pathlib import Path
from typing import Any

from . import log, paths, prefs

NAME_RE = re.compile(r"^[a-z0-9][a-z0-9-]{0,31}$")
SETTINGS_SCHEMA = 1
BASELINE_VERSION = "2026.10-preview.1"
USER_JS_HEADER = (
    "Generated by the Nulavio launcher on every start. Do not edit:\n"
    "changes here are overwritten. Use Settings, about:config, or\n"
    "`nulavio` commands instead. Source: browser/config/prefs/."
)


ENGINE_NAMES = {"nulavio", "nulavio-bin", "firefox", "firefox-bin"}


def _reused_pid(pid: int, lock: Path, profile_dir: Path) -> bool:
    """Whether `pid` is a later process that got the number of the engine that made the lock.

    It must have started after the lock was made *and* not look like an engine for this
    profile. The start time alone is not enough: a step of the wall clock (time sync, a manual
    correction) moves it, and a live engine must never be taken for gone (autolock would
    unmount its profile). A process caught in the middle of exec shows an empty command line and
    is taken for another one: the engine that made the lock is past that point (#280).
    """
    if not _started_after(pid, lock):
        return False
    try:
        if Path(os.readlink(f"/proc/{pid}/exe")).name in ENGINE_NAMES:
            return False
        if str(profile_dir) in Path(f"/proc/{pid}/cmdline").read_bytes().decode(errors="replace").split("\0"):
            return False
    except OSError:
        return False
    return True


def _started_after(pid: int, lock: Path) -> bool:
    """Whether process `pid` started after the lock was made (by the wall clock)."""
    try:
        fields = Path(f"/proc/{pid}/stat").read_text().rsplit(")", 1)[1].split()
        started_ticks = int(fields[19])  # field 22, starttime, in clock ticks after boot
        uptime = float(Path("/proc/uptime").read_text().split()[0])
        started = time.time() - uptime + started_ticks / os.sysconf("SC_CLK_TCK")
        return started > os.lstat(lock).st_mtime + 2.0  # slack for clock rounding
    except (OSError, ValueError, IndexError):
        return False


class ProfileError(RuntimeError):
    pass


class ProfileInUse(ProfileError):
    pass


@dataclass
class Profile:
    name: str
    path: Path

    @property
    def meta_dir(self) -> Path:
        return self.path / "nulavio"

    @property
    def settings_path(self) -> Path:
        return self.meta_dir / "settings.json"

    @property
    def startpage_dir(self) -> Path:
        return self.meta_dir / "startpage"

    @property
    def startpage_url(self) -> str:
        return (self.startpage_dir / "index.html").as_uri()

    # -- settings ---------------------------------------------------------
    def load_settings(self) -> dict[str, Any]:
        try:
            # The folder too: the browser can write the profile, and a link there could lead to another profile's.
            paths.check_private(self.meta_dir, paths.PRIVATE_DIR_MODE)
            data = json.loads(paths.read_private_file(self.settings_path).decode("utf-8"))
        except FileNotFoundError:
            raise ProfileError(f"profile '{self.name}' has no Nulavio settings; run `nulavio setup`") from None
        except ValueError:  # not UTF-8, or not JSON
            raise ProfileError(f"unreadable Nulavio settings in {self.settings_path}") from None
        if not isinstance(data, dict):
            raise ProfileError(f"unreadable Nulavio settings in {self.settings_path}")
        if data.get("schema") != SETTINGS_SCHEMA:
            raise ProfileError(f"unsupported settings schema in {self.settings_path}")
        return data

    def save_settings(self, data: dict[str, Any]) -> None:
        paths.ensure_private_dir(self.meta_dir)
        paths.write_private_file(self.settings_path, json.dumps(data, indent=2, sort_keys=True) + "\n")

    # -- state ------------------------------------------------------------
    def exists(self) -> bool:
        return self.settings_path.exists()

    def running_pid(self) -> int | None:
        """PID of the engine using this profile, from the engine's lock symlink."""
        lock = self.path / "lock"
        try:
            target = os.readlink(lock)
        except OSError:
            return None
        # Firefox on Linux: "<ip>:+<pid>"
        match = re.search(r":\+(\d+)$", target)
        if not match:
            return None
        pid = int(match.group(1))
        try:
            os.kill(pid, 0)
        except ProcessLookupError:
            return None  # stale lock after a crash
        except PermissionError:
            return pid
        if _reused_pid(pid, lock, self.path):
            return None  # the engine is gone and another process got its PID (audit V7)
        return pid

    def require_not_running(self) -> None:
        pid = self.running_pid()
        if pid:
            raise ProfileInUse(f"profile '{self.name}' is open (pid {pid}); close Nulavio first")


def validate_name(name: str) -> str:
    if not NAME_RE.match(name):
        raise ProfileError("profile names: 1-32 chars, lowercase letters, digits and '-', not starting with '-'")
    return name


def get(name: str) -> Profile:
    validate_name(name)
    return Profile(name=name, path=paths.profiles_root() / name)


def list_profiles() -> list[Profile]:
    root = paths.profiles_root()
    if not root.is_dir():
        return []
    return [get(p.name) for p in sorted(root.iterdir()) if p.is_dir() and NAME_RE.match(p.name)]


def baseline_prefs() -> list[prefs.Pref]:
    return prefs.parse_annotated(paths.config_dir() / "prefs" / "baseline.js")


def load_providers() -> dict[str, Any]:
    return json.loads((paths.config_dir() / "providers.json").read_text(encoding="utf-8"))


def create(name: str, *, provider: str = "builtin", inside_container: bool = False) -> Profile:
    """A new profile. `inside_container`: the directory is an empty, freshly mounted encrypted volume."""
    profile = get(name)
    fresh_volume = inside_container and profile.path.is_dir() and all(p.name == ".nulavio-vault" for p in profile.path.iterdir())
    if profile.path.exists() and not fresh_volume:
        raise ProfileError(f"profile '{name}' already exists at {profile.path}")
    providers = load_providers()["providers"]
    if provider not in providers:
        raise ProfileError(f"unknown provider '{provider}' (choose: {', '.join(providers)})")
    paths.ensure_private_dir(paths.profiles_root())
    paths.ensure_private_dir(profile.path)
    paths.ensure_private_dir(profile.meta_dir)
    now = _dt.datetime.now(_dt.UTC).isoformat(timespec="seconds")
    profile.save_settings(
        {
            "schema": SETTINGS_SCHEMA,
            "created": now,
            "baseline_version": BASELINE_VERSION,
            "provider": provider,
            "locale": ui_language(),
            "seeded": {},
            "pending_prefs": {},
        }
    )
    set_provider(profile, provider, _creating=True)
    log.event("profile.create", profile=name, provider=provider)
    return profile


def set_provider(profile: Profile, provider: str, *, _creating: bool = False) -> dict[str, Any]:
    """Select the credential provider; queues the matching engine prefs."""
    providers = load_providers()["providers"]
    if provider not in providers:
        raise ProfileError(f"unknown provider '{provider}' (choose: {', '.join(providers)})")
    if not _creating:
        profile.require_not_running()
    settings = profile.load_settings()
    settings["provider"] = provider
    # Provider prefs are explicit user decisions: queue them even if seeded.
    settings.setdefault("pending_prefs", {}).update(providers[provider]["prefs"])
    profile.save_settings(settings)
    log.event("provider.set", profile=profile.name, provider=provider)
    return providers[provider]


def sync_langpack(profile: Profile, source: Path | None) -> bool:
    """Copy the engine's own signed language pack into the profile when it changed.

    Language packs must match the engine version exactly; after an engine
    update the distribution ships a new one and this refreshes the copy.
    Returns True if the profile copy was written.
    """
    if source is None:
        return False
    ext_dir = paths.ensure_private_dir(profile.path / "extensions")
    target = ext_dir / source.name
    data = source.read_bytes()
    try:
        if paths.read_private_file(target) == data:
            return False
    except FileNotFoundError:
        pass
    paths.write_private_file(target, data)
    log.event("langpack.sync", profile=profile.name, langpack=source.name)
    return True


def _variables(profile: Profile) -> dict[str, str]:
    return {"STARTPAGE_URL": profile.startpage_url}


def seed_history() -> dict[str, list[prefs.PrefValue]]:
    """Earlier values the baseline shipped for a seed pref whose value changed (seed-history.json)."""
    try:
        data = json.loads((paths.config_dir() / "prefs" / "seed-history.json").read_text(encoding="utf-8"))
    except FileNotFoundError:
        return {}
    return data.get("earlier", {})


def _digest(value: prefs.PrefValue) -> str:
    """Of a value as prefs.js writes it, so that true and 1 are two values."""
    return hashlib.sha256(prefs.format_value(value).encode()).hexdigest()


# In settings["seeded_values"], for a value that is the person's: this, then the digest of the baseline's value
# when the launcher last had the profile's value as its own (empty for a profile seeded before #384, where that
# is not known). It says whether the baseline has moved since the person chose (default_moved).
KEPT = "kept:"


# A seed pref the Nulavio build's Shell rewrites for a setting of the person's, with the pref where the Shell records
# what it wrote (NulavioFingerprinting.sys.mjs: the set of protections without three entries, while "let sites see my
# motion and contrast preferences" is on). Such a value is neither the launcher's nor a set the person wrote, and the
# Shell brings it up to date itself at each start. Without this it could be taken for an earlier value the baseline
# shipped, which it happens to equal (review of #400).
SHELL_WRITTEN = {"privacy.fingerprintingProtection.overrides": "nulavio.fingerprinting.overridesWritten"}


def seed_states(profile: Profile, settings: dict[str, Any]) -> dict[str, tuple[str, prefs.PrefValue]]:
    """Each seed pref of the baseline: (where the profile stands, the baseline's value for this profile).

    - "new": never seeded here; the next launch writes it.
    - "current": the profile has the baseline's value.
    - "follows": the profile has a value the launcher wrote and nobody changed, and the baseline's value has
      changed since; the next launch writes the baseline's.
    - "kept": the profile has a value the person chose; it stays.
    - "managed": the profile has a value the Nulavio build's Shell wrote for a setting of the person's
      (SHELL_WRITTEN); the Shell keeps it up to date and the launcher leaves it.
    - "default": prefs.js has no value, so the engine's default applies. It stays that way, with one
      exception: a true/false pref whose baseline value changed since the launcher last looked is "follows".
      The engine does not save a value equal to its default, so for a true/false pref a missing value is
      either what the launcher seeded or the one other value, which the baseline now asks for.

    How a value is known to be the launcher's: its digest is the one recorded when the launcher wrote it
    (settings["seeded_values"]). A profile seeded before digests were recorded (#384) is recognised by
    seed_history(), the earlier values the baseline shipped, the first time it is looked at.
    """
    variables = _variables(profile)
    seeded = settings.get("seeded", {})
    written = settings.get("seeded_values", {})
    history = seed_history()
    have = prefs.read_user_prefs(profile.path / "prefs.js")
    states: dict[str, tuple[str, prefs.PrefValue]] = {}
    for pref in baseline_prefs():
        if pref.mode != "seed":
            continue
        want = prefs.substitute(pref.value, variables)
        if pref.name not in seeded:
            state = "new"
        elif pref.name not in have:
            recorded = written.get(pref.name, KEPT)
            changed = not recorded.startswith(KEPT) and recorded != _digest(want)
            state = "follows" if changed and isinstance(want, bool) else "default"
        elif _digest(have[pref.name]) == _digest(want):
            state = "current"
        elif pref.name in SHELL_WRITTEN and have.get(SHELL_WRITTEN[pref.name]) == have[pref.name]:
            state = "managed"
        elif pref.name in written:
            state = "follows" if written[pref.name] == _digest(have[pref.name]) else "kept"
        else:
            earlier = {_digest(prefs.substitute(value, variables)) for value in history.get(pref.name, [])}
            state = "follows" if _digest(have[pref.name]) in earlier else "kept"
        states[pref.name] = (state, want)
    return states


def default_moved(settings: dict[str, Any], name: str, want: prefs.PrefValue) -> bool:
    """For a seed pref whose value in the profile is the person's ("kept"): whether the baseline's value changed
    after they chose, so that what the baseline now asks for is not in effect there."""
    recorded = settings.get("seeded_values", {}).get(name)
    if recorded is None:  # not looked at since #384: only the list of earlier values can say
        return name in seed_history()
    # With the prefix or not yet: the person may have changed the value since the last launch (review of #400).
    return recorded.removeprefix(KEPT) != _digest(want)


def prepare_for_launch(profile: Profile, context: dict[str, str]) -> list[str]:
    """Apply pending seed prefs, render user.js and the start page.

    The preview's userChrome.css, which an earlier launcher wrote into the profile, is removed: the Nulavio build
    ships its window theme, and the preview is no longer offered (#464).

    Must run while the profile is not in use. Returns the names of prefs that
    were newly written into prefs.js.
    """
    profile.require_not_running()
    settings = profile.load_settings()
    variables = _variables(profile)
    seeded: dict[str, str] = settings.setdefault("seeded", {})
    states = seed_states(profile, settings)
    # For each seed pref: the digest of what the launcher last wrote or found, or KEPT for the person's value.
    first_look = "seeded_values" not in settings
    changed_before = seed_history()
    written: dict[str, str] = settings.setdefault("seeded_values", {})
    to_write: list[tuple[str, prefs.PrefValue]] = []
    followed = []
    for name, (state, want) in states.items():
        if state in ("new", "follows"):
            to_write.append((name, want))
            if state == "new":
                seeded[name] = settings.get("baseline_version", BASELINE_VERSION)
            else:
                followed.append(name)
        if state != "kept":
            # Also for a missing value: it is looked at again when the baseline changes.
            written[name] = _digest(want)
        elif not written.get(name, "").startswith(KEPT):
            # Found to be the person's now. The baseline as it was when the value was last the launcher's stays
            # on record. For a profile from before #384 that is not known when the baseline's value has ever
            # changed; when it never has, it is today's.
            unknown = first_look and name in changed_before
            written[name] = KEPT + ("" if unknown else written.get(name, _digest(want)))
    if followed:
        log.event("prefs.followed_baseline", profile=profile.name, prefs=sorted(followed))
    for name, value in settings.get("pending_prefs", {}).items():
        to_write.append((name, value))
    if to_write:
        _append_prefs_js(profile, to_write)
    settings["pending_prefs"] = {}

    enforced = [(p.name, prefs.substitute(p.value, variables)) for p in baseline_prefs() if p.mode == "enforce"]
    _remove_preview_theme(profile)
    paths.write_private_file(profile.path / "user.js", prefs.render(enforced, USER_JS_HEADER))
    render_startpage(profile, settings, context)
    profile.save_settings(settings)
    return [name for name, _ in to_write]


@contextlib.contextmanager
def prefs_js_lock(profile_dir: Path, *, wait: float | None = None):
    """Held while the launcher reads and then replaces a profile's prefs.js: `nulavio run` appending seed and pending
    prefs here, and the AI Bridge taking its temporary prefs out (ai/workspace.py, ProfileTarget). Each then reads the
    file as the other left it, and neither puts back a copy from before the other's change (review of #826).

    An exclusive flock on the profile's folder, which adds no file to it. Where the folder cannot be opened or
    locked, the change is made without it, as before. With `wait`, a lock still held by another after that many
    seconds raises TimeoutError, and nothing is changed (review 2 of #826)."""
    try:
        fd = os.open(profile_dir, os.O_RDONLY | os.O_DIRECTORY | os.O_NOFOLLOW | os.O_CLOEXEC)
    except OSError:
        yield
        return
    try:
        deadline = None if wait is None else time.monotonic() + wait
        while True:
            try:
                fcntl.flock(fd, fcntl.LOCK_EX | (0 if deadline is None else fcntl.LOCK_NB))
            except BlockingIOError:
                if time.monotonic() >= deadline:
                    raise TimeoutError(f"{profile_dir}: prefs.js is being changed by another launcher") from None
                time.sleep(0.05)
                continue
            except OSError:
                pass  # a file system that does not lock
            break
        yield
    finally:
        os.close(fd)  # releases the lock


def _append_prefs_js(profile: Profile, items: list[tuple[str, prefs.PrefValue]]) -> None:
    target = profile.path / "prefs.js"
    with prefs_js_lock(profile.path):
        # Checked again under the lock, which may have been waited for behind the AI Bridge: a profile an engine
        # opened meanwhile is that engine's (review 2 of #826).
        profile.require_not_running()
        try:
            # Never through a symlink or from a FIFO: the browser writes this folder, and this runs outside its
            # confinement.
            existing = paths.read_private_file(target).decode("utf-8")
        except FileNotFoundError:
            existing = ""
        except UnicodeDecodeError:
            raise ProfileError(f"{target} is not valid UTF-8; the launcher does not append to it") from None
        stamp = _dt.datetime.now(_dt.UTC).isoformat(timespec="seconds")
        block = [f"// Nulavio launcher: applied {len(items)} pref(s) at {stamp}"]
        block += [prefs.format_pref(name, value) for name, value in items]
        if existing and not existing.endswith("\n"):
            existing += "\n"
        paths.write_private_file(target, existing + "\n".join(block) + "\n")


PREVIEW_THEME_MARKER = "Nulavio Preview chrome theme (Track A, userChrome.css)"


def _remove_preview_theme(profile: Profile) -> None:
    """Delete the launcher's own userChrome.css; never a file the user wrote."""
    css = profile.path / "chrome" / "userChrome.css"
    own = css.is_file() and not css.is_symlink() and not css.parent.is_symlink()  # never another profile's
    if own and PREVIEW_THEME_MARKER in css.read_text(encoding="utf-8", errors="replace")[:400]:
        css.unlink()
        log.event("theme.preview_removed", profile=profile.name)


def ui_language() -> str:
    """Pick the start page language from the POSIX locale (pt* -> pt-BR, else en)."""
    for var in ("LC_ALL", "LC_MESSAGES", "LANG"):
        value = os.environ.get(var, "")
        if value:
            return "pt-BR" if value.lower().startswith("pt") else "en"
    return "en"


def _filter_text(context: dict[str, str], strings: dict[str, str]) -> str:
    label = context.get("filter")
    if not label:
        return strings.get("T_FILTER_NONE", "none")
    suffix = strings.get(f"T_FILTER_STATE_{context.get('filter_state', '').upper()}")
    return f"{label} — {suffix}" if suffix else label


def _addons_key(engine: str) -> str:
    """The letter of the add-ons shortcut (Ctrl+Shift+…) in this engine: Firefox 159 moved it from A
    to F (Ctrl+Shift+A searches tabs there). The page is static, so the launcher picks the letter;
    an engine label with no version gets the letter of the oldest supported engine."""
    # The version is the label's last word and may not end in digits ("160.0a1", "159.0esr", "160.0-0.3"): its
    # leading number.
    version = re.search(r"(?:^|\s)(\d+)[\w.+~-]*\s*$", engine)
    return "F" if version and int(version.group(1)) >= 159 else "A"


def render_startpage(profile: Profile, settings: dict[str, Any], context: dict[str, str]) -> Path:
    """Generate the per-profile local start page from browser/startpage/.

    Only facts known locally are shown (profile name, engine version,
    installed filter, provider choice). No counters, no remote content.
    """
    template_dir = paths.repo_root() / "browser" / "startpage"
    out = paths.ensure_private_dir(profile.startpage_dir)
    providers = load_providers()["providers"]
    provider = settings.get("provider", "builtin")
    strings = json.loads((template_dir / "strings.json").read_text(encoding="utf-8"))
    language = settings.get("locale") or ui_language()
    values = dict(strings.get(language, strings["en"]))
    engine = context.get("engine", "")
    if engine.startswith("Nulavio"):
        # The Nulavio build carries its patch series: neither the note nor the footer may call it
        # the unmodified engine (audit 2026-11 P-01).
        values["T_ENGINE_NOTE"] = values["T_ENGINE_NOTE_NULAVIO"]
        values["T_FOOTER"] = values["T_FOOTER_NULAVIO"]
    values.update(
        {
            "PROFILE": profile.name,
            "ENGINE": context.get("engine", "unknown engine"),
            "KEY_ADDONS": _addons_key(engine),
            "FILTER": _filter_text(context, values),
            "PROVIDER": values.get(
                "T_PROVIDER_" + provider.upper().replace("-", "_"),
                providers.get(provider, {}).get("label", provider),
            ),
            "BASELINE": settings.get("baseline_version", BASELINE_VERSION),
        }
    )
    page = (template_dir / "index.html").read_text(encoding="utf-8")
    for key, value in values.items():
        page = page.replace(f"{{{{{key}}}}}", html.escape(value))
    if "{{" in page:
        raise ProfileError("start page template has unknown placeholders")
    paths.write_private_file(out / "index.html", page)
    for asset in ("startpage.css", "tokens.css"):
        paths.write_private_file(out / asset, (template_dir / asset).read_text(encoding="utf-8"))
    for svg in ("nulavio-symbol.svg", "nulavio-symbol-dark-on-light.svg"):
        source = paths.assets_dir() / "logo" / svg
        if source.exists():
            paths.write_private_file(out / svg, source.read_bytes())
    return out / "index.html"


def delete(profile: Profile) -> None:
    profile.require_not_running()
    if not profile.path.exists():
        raise ProfileError(f"profile '{profile.name}' does not exist")
    root = paths.profiles_root().resolve()
    target = profile.path.resolve()
    if target.parent != root:
        raise ProfileError("refusing to delete a path outside the profiles directory")
    shutil.rmtree(target)
    log.event("profile.delete", profile=profile.name)
