"""Nulavio profiles: isolated engine profiles plus Nulavio settings.

Layout of ``$XDG_DATA_HOME/nulavio/profiles/<name>/`` (all 0700/0600):

    prefs.js, user.js, extensions/ ...   engine-owned profile files
    chrome/userChrome.css                preview theme (optional)
    nulavio/settings.json                Nulavio choices for this profile
    nulavio/startpage/                   generated local start page

Preference strategy (see browser/config/prefs/baseline.js):
* ``seed`` prefs are appended to prefs.js only while the profile is *not*
  running, once per pref; afterwards they are ordinary user choices.
* ``enforce`` prefs are rendered into user.js on every launch.
"""

from __future__ import annotations

import datetime as _dt
import html
import json
import os
import re
import shutil
import time
from dataclasses import dataclass
from pathlib import Path
from typing import Any

from . import log, paths, prefs

NAME_RE = re.compile(r"^[a-z0-9][a-z0-9-]{0,31}$")
SETTINGS_SCHEMA = 1
BASELINE_VERSION = "2026.10-preview.1"
USER_JS_HEADER = (
    "Generated by the Nulavio launcher on every start. Do not edit:\n"
    "changes here are overwritten. Use Settings, about:config, or\n"
    "`nulavio` commands instead. Source: browser/config/prefs/."
)


ENGINE_NAMES = {"nulavio", "nulavio-bin", "firefox", "firefox-bin"}


def _reused_pid(pid: int, lock: Path, profile_dir: Path) -> bool:
    """Whether `pid` is a later process that got the number of the engine that made the lock.

    It must have started after the lock was made *and* not look like an engine for this
    profile. The start time alone is not enough: a step of the wall clock (time sync, a manual
    correction) moves it, and a live engine must never be taken for gone (autolock would
    unmount its profile).
    """
    if not _started_after(pid, lock):
        return False
    try:
        if Path(os.readlink(f"/proc/{pid}/exe")).name in ENGINE_NAMES:
            return False
        if str(profile_dir) in Path(f"/proc/{pid}/cmdline").read_bytes().decode(errors="replace").split("\0"):
            return False
    except OSError:
        return False
    return True


def _started_after(pid: int, lock: Path) -> bool:
    """Whether process `pid` started after the lock was made (by the wall clock)."""
    try:
        fields = Path(f"/proc/{pid}/stat").read_text().rsplit(")", 1)[1].split()
        started_ticks = int(fields[19])  # field 22, starttime, in clock ticks after boot
        uptime = float(Path("/proc/uptime").read_text().split()[0])
        started = time.time() - uptime + started_ticks / os.sysconf("SC_CLK_TCK")
        return started > os.lstat(lock).st_mtime + 2.0  # slack for clock rounding
    except (OSError, ValueError, IndexError):
        return False


class ProfileError(RuntimeError):
    pass


class ProfileInUse(ProfileError):
    pass


@dataclass
class Profile:
    name: str
    path: Path

    @property
    def meta_dir(self) -> Path:
        return self.path / "nulavio"

    @property
    def settings_path(self) -> Path:
        return self.meta_dir / "settings.json"

    @property
    def startpage_dir(self) -> Path:
        return self.meta_dir / "startpage"

    @property
    def startpage_url(self) -> str:
        return (self.startpage_dir / "index.html").as_uri()

    # -- settings ---------------------------------------------------------
    def load_settings(self) -> dict[str, Any]:
        try:
            data = json.loads(self.settings_path.read_text(encoding="utf-8"))
        except FileNotFoundError:
            raise ProfileError(f"profile '{self.name}' has no Nulavio settings; run `nulavio setup`") from None
        if data.get("schema") != SETTINGS_SCHEMA:
            raise ProfileError(f"unsupported settings schema in {self.settings_path}")
        return data

    def save_settings(self, data: dict[str, Any]) -> None:
        paths.ensure_private_dir(self.meta_dir)
        paths.write_private_file(self.settings_path, json.dumps(data, indent=2, sort_keys=True) + "\n")

    # -- state ------------------------------------------------------------
    def exists(self) -> bool:
        return self.settings_path.exists()

    def running_pid(self) -> int | None:
        """PID of the engine using this profile, from the engine's lock symlink."""
        lock = self.path / "lock"
        try:
            target = os.readlink(lock)
        except OSError:
            return None
        # Firefox on Linux: "<ip>:+<pid>"
        match = re.search(r":\+(\d+)$", target)
        if not match:
            return None
        pid = int(match.group(1))
        try:
            os.kill(pid, 0)
        except ProcessLookupError:
            return None  # stale lock after a crash
        except PermissionError:
            return pid
        if _reused_pid(pid, lock, self.path):
            return None  # the engine is gone and another process got its PID (audit V7)
        return pid

    def require_not_running(self) -> None:
        pid = self.running_pid()
        if pid:
            raise ProfileInUse(f"profile '{self.name}' is open (pid {pid}); close Nulavio first")


def validate_name(name: str) -> str:
    if not NAME_RE.match(name):
        raise ProfileError("profile names: 1-32 chars, lowercase letters, digits and '-', not starting with '-'")
    return name


def get(name: str) -> Profile:
    validate_name(name)
    return Profile(name=name, path=paths.profiles_root() / name)


def list_profiles() -> list[Profile]:
    root = paths.profiles_root()
    if not root.is_dir():
        return []
    return [get(p.name) for p in sorted(root.iterdir()) if p.is_dir() and NAME_RE.match(p.name)]


def baseline_prefs() -> list[prefs.Pref]:
    return prefs.parse_annotated(paths.config_dir() / "prefs" / "baseline.js")


def theme_prefs() -> list[prefs.Pref]:
    return prefs.parse_annotated(paths.config_dir() / "prefs" / "theme.js")


def load_providers() -> dict[str, Any]:
    return json.loads((paths.config_dir() / "providers.json").read_text(encoding="utf-8"))


def create(name: str, *, provider: str = "builtin", theme: bool = True, inside_container: bool = False) -> Profile:
    """A new profile. `inside_container`: the directory is an empty, freshly mounted encrypted volume."""
    profile = get(name)
    fresh_volume = inside_container and profile.path.is_dir() and all(p.name == ".nulavio-vault" for p in profile.path.iterdir())
    if profile.path.exists() and not fresh_volume:
        raise ProfileError(f"profile '{name}' already exists at {profile.path}")
    providers = load_providers()["providers"]
    if provider not in providers:
        raise ProfileError(f"unknown provider '{provider}' (choose: {', '.join(providers)})")
    paths.ensure_private_dir(paths.profiles_root())
    paths.ensure_private_dir(profile.path)
    paths.ensure_private_dir(profile.meta_dir)
    now = _dt.datetime.now(_dt.UTC).isoformat(timespec="seconds")
    profile.save_settings(
        {
            "schema": SETTINGS_SCHEMA,
            "created": now,
            "baseline_version": BASELINE_VERSION,
            "provider": provider,
            "theme": theme,
            "locale": ui_language(),
            "seeded": {},
            "pending_prefs": {},
        }
    )
    set_provider(profile, provider, _creating=True)
    log.event("profile.create", profile=name, provider=provider, theme=theme)
    return profile


def set_provider(profile: Profile, provider: str, *, _creating: bool = False) -> dict[str, Any]:
    """Select the credential provider; queues the matching engine prefs."""
    providers = load_providers()["providers"]
    if provider not in providers:
        raise ProfileError(f"unknown provider '{provider}' (choose: {', '.join(providers)})")
    if not _creating:
        profile.require_not_running()
    settings = profile.load_settings()
    settings["provider"] = provider
    # Provider prefs are explicit user decisions: queue them even if seeded.
    settings.setdefault("pending_prefs", {}).update(providers[provider]["prefs"])
    profile.save_settings(settings)
    log.event("provider.set", profile=profile.name, provider=provider)
    return providers[provider]


def set_theme(profile: Profile, enabled: bool) -> None:
    profile.require_not_running()
    settings = profile.load_settings()
    settings["theme"] = enabled
    profile.save_settings(settings)
    if not enabled:
        css = profile.path / "chrome" / "userChrome.css"
        if css.exists():
            css.unlink()
    log.event("theme.set", profile=profile.name, enabled=enabled)


def sync_langpack(profile: Profile, source: Path | None) -> bool:
    """Copy the engine's own signed language pack into the profile when it changed.

    Language packs must match the engine version exactly; after an engine
    update the distribution ships a new one and this refreshes the copy.
    Returns True if the profile copy was written.
    """
    if source is None:
        return False
    ext_dir = paths.ensure_private_dir(profile.path / "extensions")
    target = ext_dir / source.name
    data = source.read_bytes()
    if target.exists() and target.read_bytes() == data:
        return False
    paths.write_private_file(target, data)
    log.event("langpack.sync", profile=profile.name, langpack=source.name)
    return True


def _variables(profile: Profile) -> dict[str, str]:
    return {"STARTPAGE_URL": profile.startpage_url}


def prepare_for_launch(profile: Profile, context: dict[str, str], builtin_theme: bool = False) -> list[str]:
    """Apply pending seed prefs, render user.js, theme and start page.

    ``builtin_theme``: the engine (the Nulavio build) ships its own window
    theme, so the preview userChrome.css is not installed and any copy the
    launcher wrote earlier is removed (it would override the built-in theme).

    Must run while the profile is not in use. Returns the names of prefs that
    were newly written into prefs.js.
    """
    profile.require_not_running()
    settings = profile.load_settings()
    variables = _variables(profile)
    seeded: dict[str, str] = settings.setdefault("seeded", {})
    to_write: list[tuple[str, prefs.PrefValue]] = []
    for pref in baseline_prefs():
        if pref.mode == "seed" and pref.name not in seeded:
            to_write.append((pref.name, prefs.substitute(pref.value, variables)))
            seeded[pref.name] = settings.get("baseline_version", BASELINE_VERSION)
    for name, value in settings.get("pending_prefs", {}).items():
        to_write.append((name, value))
    if to_write:
        _append_prefs_js(profile, to_write)
    settings["pending_prefs"] = {}

    enforced = [(p.name, prefs.substitute(p.value, variables)) for p in baseline_prefs() if p.mode == "enforce"]
    if builtin_theme:
        _remove_preview_theme(profile)
    elif settings.get("theme", True):
        enforced += [(p.name, p.value) for p in theme_prefs()]
        _install_theme(profile)
    paths.write_private_file(profile.path / "user.js", prefs.render(enforced, USER_JS_HEADER))
    render_startpage(profile, settings, context)
    profile.save_settings(settings)
    return [name for name, _ in to_write]


def _append_prefs_js(profile: Profile, items: list[tuple[str, prefs.PrefValue]]) -> None:
    target = profile.path / "prefs.js"
    existing = target.read_text(encoding="utf-8") if target.exists() else ""
    stamp = _dt.datetime.now(_dt.UTC).isoformat(timespec="seconds")
    block = [f"// Nulavio launcher: applied {len(items)} pref(s) at {stamp}"]
    block += [prefs.format_pref(name, value) for name, value in items]
    if existing and not existing.endswith("\n"):
        existing += "\n"
    paths.write_private_file(target, existing + "\n".join(block) + "\n")


PREVIEW_THEME_MARKER = "Nulavio Preview chrome theme (Track A, userChrome.css)"


def _install_theme(profile: Profile) -> None:
    source = paths.repo_root() / "browser" / "theme" / "userChrome.css"
    chrome_dir = paths.ensure_private_dir(profile.path / "chrome")
    paths.write_private_file(chrome_dir / "userChrome.css", source.read_text(encoding="utf-8"))


def _remove_preview_theme(profile: Profile) -> None:
    """Delete the launcher's own userChrome.css; never a file the user wrote."""
    css = profile.path / "chrome" / "userChrome.css"
    if css.is_file() and not css.is_symlink() and PREVIEW_THEME_MARKER in css.read_text(encoding="utf-8", errors="replace")[:400]:
        css.unlink()
        log.event("theme.preview_removed", profile=profile.name)


def ui_language() -> str:
    """Pick the start page language from the POSIX locale (pt* -> pt-BR, else en)."""
    for var in ("LC_ALL", "LC_MESSAGES", "LANG"):
        value = os.environ.get(var, "")
        if value:
            return "pt-BR" if value.lower().startswith("pt") else "en"
    return "en"


def _filter_text(context: dict[str, str], strings: dict[str, str]) -> str:
    label = context.get("filter")
    if not label:
        return strings.get("T_FILTER_NONE", "none")
    suffix = strings.get(f"T_FILTER_STATE_{context.get('filter_state', '').upper()}")
    return f"{label} — {suffix}" if suffix else label


def _addons_key(engine: str) -> str:
    """The letter of the add-ons shortcut (Ctrl+Shift+…) in this engine: Firefox 159 moved it from A
    to F (Ctrl+Shift+A searches tabs there). The page is static, so the launcher picks the letter;
    an engine label with no version gets the letter of the oldest supported engine."""
    version = re.search(r"(\d+)(?:\.\d+)*\s*$", engine)
    return "F" if version and int(version.group(1)) >= 159 else "A"


def render_startpage(profile: Profile, settings: dict[str, Any], context: dict[str, str]) -> Path:
    """Generate the per-profile local start page from browser/startpage/.

    Only facts known locally are shown (profile name, engine version,
    installed filter, provider choice). No counters, no remote content.
    """
    template_dir = paths.repo_root() / "browser" / "startpage"
    out = paths.ensure_private_dir(profile.startpage_dir)
    providers = load_providers()["providers"]
    provider = settings.get("provider", "builtin")
    strings = json.loads((template_dir / "strings.json").read_text(encoding="utf-8"))
    language = settings.get("locale") or ui_language()
    values = dict(strings.get(language, strings["en"]))
    engine = context.get("engine", "")
    if engine.startswith("Nulavio"):
        # The Nulavio build carries its patch series: neither the note nor the footer may call it
        # the unmodified engine (audit 2026-11 P-01).
        values["T_ENGINE_NOTE"] = values["T_ENGINE_NOTE_NULAVIO"]
        values["T_FOOTER"] = values["T_FOOTER_NULAVIO"]
    values.update(
        {
            "PROFILE": profile.name,
            "ENGINE": context.get("engine", "unknown engine"),
            "KEY_ADDONS": _addons_key(engine),
            "FILTER": _filter_text(context, values),
            "PROVIDER": values.get(
                "T_PROVIDER_" + provider.upper().replace("-", "_"),
                providers.get(provider, {}).get("label", provider),
            ),
            "BASELINE": settings.get("baseline_version", BASELINE_VERSION),
        }
    )
    page = (template_dir / "index.html").read_text(encoding="utf-8")
    for key, value in values.items():
        page = page.replace(f"{{{{{key}}}}}", html.escape(value))
    if "{{" in page:
        raise ProfileError("start page template has unknown placeholders")
    paths.write_private_file(out / "index.html", page)
    for asset in ("startpage.css", "tokens.css"):
        paths.write_private_file(out / asset, (template_dir / asset).read_text(encoding="utf-8"))
    for svg in ("nulavio-symbol.svg", "nulavio-symbol-dark-on-light.svg"):
        source = paths.assets_dir() / "logo" / svg
        if source.exists():
            paths.write_private_file(out / svg, source.read_bytes())
    return out / "index.html"


def delete(profile: Profile) -> None:
    profile.require_not_running()
    if not profile.path.exists():
        raise ProfileError(f"profile '{profile.name}' does not exist")
    root = paths.profiles_root().resolve()
    target = profile.path.resolve()
    if target.parent != root:
        raise ProfileError("refusing to delete a path outside the profiles directory")
    shutil.rmtree(target)
    log.event("profile.delete", profile=profile.name)
