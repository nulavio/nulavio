SITE_PREVIEWS = ("site/assets/og-en.png", "site/assets/og-pt.png")  # from scripts/site/og-template.html
PREVIEW_WIDTHS = (600, 300)  # assumed: a card in a timeline or a chat, and a small one
PREVIEW_SQUARE = 158  # assumed: a centre square, as for a small thumbnail beside a title


SHEET_GREY, SHEET_INK = "#888888", "#10161C"  # the sheet's ground, and its labels on it (5.4:1)
SHEET_LABEL = 44  # the height of a row of labels


def link_previews(out_dir: Path, sheet: Path) -> None:
    """The three link-preview images side by side (#199), one to a column: GitHub's, then the site's
    in English and in Portuguese. Each row has a label over every picture, on the sheet's grey and
    never over a picture. First row: each 600 px wide. Second row: each 300 px wide, with its centre
    square at 158 px beside it. Third row: each cut to 16:9 at its centre. Fourth row: the GitHub
    image cut to 1.91:1 (the site's are 1.905:1 already, so that cut takes nothing from them). The
    images are resampled; nothing is drawn over them. The widths and the crops are this script's
    assumption of what a network may do with a picture, read from no network's documentation, and
    the sheet is not a capture of any of them."""
    images = [out_dir / "github" / "social-preview.png", *(ROOT / rel for rel in SITE_PREVIEWS)]
    names = ["GitHub", "Site, English", "Site, Portuguese"]
    wide, small = PREVIEW_WIDTHS
    column = wide + 20
    ground = ["-background", SHEET_GREY]
    cell = [*ground, "-gravity", "center", "-extent", f"{column}x{wide * 9 // 16 + 20}"]
    row = [*ground, "+append"]

    def crop(image: Path, ratio: float) -> list[str]:
        width, height = _png_size(image)
        cut = min(width, round(height * ratio))
        return [str(image), "-gravity", "center", "-crop", f"{cut}x{height}+0+0", "+repage"]

    def labels(path: Path, what: list[str]) -> str:
        """A row of labels as a picture, one over each column; drawn as the rest of the art is."""
        spans = "".join(
            text([f"{name_} \u00b7 {said}"], 10 + i * column, SHEET_LABEL - 12, 22, 1.2, SHEET_INK, 600)
            for i, (name_, said) in enumerate(zip(names, what, strict=False))
        )
        ground_ = f'<rect width="{column * len(images)}" height="{SHEET_LABEL}" fill="{SHEET_GREY}"/>'
        path.with_suffix(".svg").write_text(
            svg(column * len(images), SHEET_LABEL, ground_ + spans, title="Labels"), encoding="utf-8"
        )
        rasterise(path.with_suffix(".svg"), path)
        return str(path)

    with tempfile.TemporaryDirectory() as tmp:
        t = Path(tmp)
        command = ["magick", labels(t / "a.png", [f"{wide} px wide"] * 3), "("]
        for image in images:
            command += ["(", str(image), "-resize", f"{wide}x", *cell, ")"]
        command += [*row, ")", labels(t / "b.png", [f"{small} px wide, and its centre square"] * 3), "("]
        for image in images:
            command += ["(", "(", str(image), "-resize", f"{small}x", ")"]
            command += ["(", *crop(image, 1), "-resize", f"{PREVIEW_SQUARE}x{PREVIEW_SQUARE}"]
            command += [*ground, "-gravity", "west", "-splice", "20x0", ")"]
            command += [
                *ground,
                "-gravity",
                "west",
                "+append",
                "-splice",
                "10x0",
                "-extent",
                f"{column}x{PREVIEW_SQUARE + 20}",
                ")",
            ]
        command += [*row, ")", labels(t / "c.png", ["cut to 16:9 at the centre"] * 3), "("]
        for image in images:
            command += ["(", *crop(image, 16 / 9), "-resize", f"{wide}x", *cell, ")"]
        command += [*row, ")", labels(t / "d.png", ["cut to 1.91:1 at the centre"]), "("]
        command += ["(", *crop(images[0], 1.91), "-resize", f"{wide}x", *cell, ")"]
        command += [*row, ")", *ground, "-gravity", "northwest", "-append", *STRIP, str(sheet)]
        subprocess.run(command, check=True)


def _png_size(path: Path) -> tuple[int, int]:
    data = path.read_bytes()[:24]
    if data[:8] != b"\x89PNG\r\n\x1a\n":
        raise ValueError(f"{path} is not a PNG")
    return int.from_bytes(data[16:20], "big"), int.from_bytes(data[20:24], "big")


def write_all(svg_only: bool = False) -> list[Path]:
    if not svg_only:
        card_rasteriser()
    written = []
    for rel, text_ in all_svgs().items():
        path = OUT / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text_, encoding="utf-8")
        written.append(path)
        if not svg_only:
            png = path.with_suffix(".png")
            (write_card if rel.startswith("github/") else rasterise)(path, png)
            written.append(png)
    if not svg_only:
        sheet = OUT / "crop-check.png"
        crop_check(OUT, sheet)
        written.append(sheet)
        sheet = OUT / "link-previews.png"
        link_previews(OUT, sheet)
        written.append(sheet)
    return written


class Busy(ValueError):
    """Another run holds the directory."""


def publish(staged: list[Path], target: Path, aside: Path) -> None:
    """Move the staged files into `target` as one set. The directory is locked for the move, so that
    two runs are never mixed; nothing is moved when a directory stands where a file is to go; and a
    move that fails puts back what the moves before it replaced. `aside`, on the same file system,
    holds the replaced files until then."""
    directory = os.open(target, os.O_RDONLY | os.O_DIRECTORY)
    try:
        try:
            fcntl.flock(directory, fcntl.LOCK_EX | fcntl.LOCK_NB)
        except BlockingIOError:
            raise Busy(f"another run is writing into {target}: nothing was written") from None
        blocked = sorted(path.name for path in staged if (target / path.name).is_dir() and not (target / path.name).is_symlink())
        if blocked:
            raise ValueError(f"{', '.join(blocked)} in {target}: a directory is where a file is to go; nothing was written")
        moved: list[tuple[Path, Path | None]] = []
        try:
            for path in staged:
                destination = target / path.name
                old = aside / path.name if os.path.lexists(destination) else None
                if old:
                    os.replace(destination, old)
                moved.append((destination, old))
                os.replace(path, destination)
        except OSError:
            for destination, old in reversed(moved):
                if old:
                    os.replace(old, destination)
                else:
                    with contextlib.suppress(FileNotFoundError):
                        os.unlink(destination)
            raise
    finally:
        os.close(directory)


def write_post(post: object, out: Path, svg_only: bool = False) -> list[Path]:
    """One post in every format, into `out`. Every format is drawn before a file is written. The
    files are made in a directory inside the nearest directory that exists (`out`, or the one it will
    be created in: the same file system, so that each move is a rename), and `out` is created and they
    are moved in together at the end (publish). A text that does not fit one format, a rasteriser that
    fails or a move that cannot be made leaves `out` as it was, and absent when it was absent.
    ImageMagick is given absolute paths, so a name that starts with "-" is not read as an option; the
    files go where the system finds `out`, links followed, and the paths returned are under `out` as
    the caller wrote it."""
    post = validate(post)
    svgs = {f"{fmt}-{post['lang']}.svg": post_svg(fmt, post) for fmt in FORMATS}
    target = Path(os.path.realpath(out))  # where the system finds `out`: ".." after a link is the link's target's parent
    missing = [path for path in (target, *target.parents) if not os.path.lexists(path)]  # deepest first
    anchor = target if not missing else missing[-1].parent
    with tempfile.TemporaryDirectory(dir=anchor, prefix=".build_social-") as staging:
        new, aside = Path(staging) / "new", Path(staging) / "old"
        new.mkdir()
        aside.mkdir()
        staged = []
        for file_name, text_ in svgs.items():
            path = new / file_name
            path.write_text(text_, encoding="utf-8")
            staged.append(path)
            if not svg_only:
                rasterise(path, path.with_suffix(".png"))
                staged.append(path.with_suffix(".png"))
        created = []
        try:
            for path in reversed(missing):
                with contextlib.suppress(FileExistsError):  # made meanwhile by another run: not this run's to remove
                    path.mkdir()
                    created.append(path)
            publish(staged, target, aside)
        except Busy:
            raise  # the directory is the other run's now
        except BaseException:
            for path in reversed(created):  # deepest first, and only while it is empty
                with contextlib.suppress(OSError):
                    path.rmdir()
            raise
    return [out / path.name for path in staged]


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--svg-only", action="store_true", help="write the SVG files only")
    sub = parser.add_subparsers(dest="command")
    one = sub.add_parser("post", help="render one post, in every format, from a JSON file")
    one.add_argument("--text", type=Path, required=True)
    one.add_argument("--out", type=Path, required=True)
    args = parser.parse_args()
    if not args.svg_only and not shutil.which("magick"):
        parser.error("need ImageMagick 7 ('magick') with librsvg to rasterise; or pass --svg-only")
    if args.command == "post":
        try:
            written = write_post(json.loads(args.text.read_text(encoding="utf-8")), args.out, args.svg_only)
        except (OSError, ValueError) as error:  # a file that cannot be read, JSON that is not, a post that is refused
            print(f"{args.text}: {error}", file=sys.stderr)
            return 1
        for path in written:
            print(path)
        return 0
    for path in write_all(args.svg_only):
        print(path.relative_to(ROOT))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
