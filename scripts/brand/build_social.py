#!/usr/bin/env python3
"""Generate Nulavio's social media art from the brand sources (#175, step 4).

Everything is drawn from build_logo.py's marks and the colours of docs/brand/tokens.json; nothing is
drawn by hand and no image is generated by a model. Writes, under docs/brand/assets/social/:

  profile/avatar.svg, avatar.png      400 x 400: the app icon's route on its tile, full bleed, so
                                      that a circle crop shows no corner (X, GitHub, Mastodon)
  profile/header-<lang>.svg, .png    1500 x 500 (X's header), en and pt-BR: the name and the tagline,
                                      kept out of the parts the avatar covers and phones crop
  posts/<format>-<lang>.svg, .png     post templates: 16x9 (1600 x 900), 1x1 (1080 x 1080),
                                      4x5 (1080 x 1350), 9x16 (1080 x 1920), in en and pt-BR
  crop-check.png                      the avatar in a circle at 400 and 48 px, and the header
                                      with the avatar's place and the phone crop drawn over it
  github/social-preview.svg, .png     1280 x 640: the repository's social preview on GitHub (#199),
                                      in English, on a solid background (the PNG has no alpha)
  link-previews.png                   the GitHub image and the site's two link-preview images
                                      (site/assets/og-en.png, og-pt.png) side by side, each row
                                      labelled: at two widths, and in the centre crops assumed

The texts are input: the templates' sample texts are SAMPLES below; a new post is one command,

  python3 -I scripts/brand/build_social.py post --text post.json --out <dir>

where post.json holds {"lang": "en", "kicker": "...", "title": "...", "body": "...", "footer": "..."}
(title and body may contain line breaks; long lines wrap at spaces, never at a no-break space). It
writes the four formats into <dir>, or nothing: a text that does not fit one of them, a rasteriser that
fails, a directory where a file is to go, or a file that cannot be moved in, leaves <dir> as it was (and
absent, when it was). Two runs into one directory at once are not mixed: the second is refused. Only a
run that is killed while it moves its files in can leave some of them.

Text is set in Noto Sans (SIL OFL; installed on most Linux desktops and in the Fedora build image),
the brand's documented fallback while Inter is not bundled. The SVG files are deterministic
(tests/unit/test_social_art.py compares them); the PNGs depend on the host's fonts and librsvg.
Rasterising needs ImageMagick 7 (`magick`) with the librsvg delegate, as build_icons.py does; the
GitHub card also needs a Q16 or an HDRI build of it (the usual one), which is checked first.

    python3 -I scripts/brand/build_social.py             all of the above
    python3 -I scripts/brand/build_social.py --svg-only  the SVG files only (no ImageMagick)

Uploading the avatar and the header to the profiles, setting the repository's social preview
(Settings, "Social preview", Edit, "Upload an image...") and posting stay with the maintainer.
"""

