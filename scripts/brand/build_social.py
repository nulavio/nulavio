#!/usr/bin/env python3
"""Generate Nulavio's social media art from the brand sources (#175, step 4).

Everything is drawn from build_logo.py's marks and the colours of docs/brand/tokens.json; nothing is
drawn by hand and no image is generated by a model. Writes, under docs/brand/assets/social/:

  profile/avatar.svg, avatar.png      400 x 400: the app icon's route on its tile, full bleed, so
                                      that a circle crop shows no corner (X, GitHub, Mastodon)
  profile/header-<lang>.svg, .png    1500 x 500 (X's header), en and pt-BR: the name and the tagline,
                                      kept out of the parts the avatar covers and phones crop
  posts/<format>-<lang>.svg, .png     post templates: 16x9 (1600 x 900), 1x1 (1080 x 1080),
                                      4x5 (1080 x 1350), 9x16 (1080 x 1920), in en and pt-BR
  crop-check.png                      the avatar in a circle at 400 and 48 px, and the header
                                      with the avatar's place and the phone crop drawn over it

The texts are input: the templates' sample texts are SAMPLES below; a new post is one command,

  python3 -I scripts/brand/build_social.py post --text post.json --out <dir>

where post.json holds {"lang": "en", "kicker": "...", "title": "...", "body": "...", "footer": "..."}
(title and body may contain line breaks; long lines wrap). It writes the four formats into <dir>.

Text is set in Noto Sans (SIL OFL; installed on most Linux desktops and in the Fedora build image),
the brand's documented fallback while Inter is not bundled. The SVG files are deterministic
(tests/unit/test_social_art.py compares them); the PNGs depend on the host's fonts and librsvg.
Rasterising needs ImageMagick 7 (`magick`) with the librsvg delegate, as build_icons.py does.

    python3 -I scripts/brand/build_social.py             all of the above
    python3 -I scripts/brand/build_social.py --svg-only  the SVG files only (no ImageMagick)

Uploading the avatar and the header to the profiles, and posting, stay with the maintainer.
"""

from __future__ import annotations

import argparse
import html
import json
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

import build_logo as bl
from contrast import flatten, resolve

ROOT = bl.ROOT
OUT = bl.ASSETS / "social"
TOKENS = ROOT / "docs" / "brand" / "tokens.json"
HEADER = "<!-- Nulavio social art. Generated by scripts/brand/build_social.py. Trademark: see docs/brand/guidelines.md. -->"
FONT = "Noto Sans, sans-serif"
STRIP = ["-strip", "-define", "png:exclude-chunks=date,time"]

_TOKENS = flatten(json.loads(TOKENS.read_text(encoding="utf-8")))


def colour(path: str) -> str:
    return resolve(_TOKENS, path).upper()


# The brand's dark scheme, its home (guidelines §9), as scripts/site/og-template.html uses it.
CANVAS = colour("color.primitive.navy.875")  # #0F1C2A
GLOW = colour("color.primitive.mint.900")  # #0E3B33
INK = colour("color.primitive.navy.50")  # Cloud White
MUTED = colour("color.primitive.navy.200")  # #BFD0D6
ACCENT = colour("color.primitive.mint.400")  # Mint Signal

# Post formats: name -> (width, height, margin, top and bottom space kept free of text).
# 9:16 keeps the top 250 px and the bottom 340 px clear, where stories put their own controls.
FORMATS = {
    "16x9": (1600, 900, 96, (0, 0)),
    "1x1": (1080, 1080, 88, (0, 0)),
    "4x5": (1080, 1350, 88, (0, 0)),
    "9x16": (1080, 1920, 88, (250, 340)),
}

# X's header, 1500 x 500. X's help pages recommend 1500 x 500 and say the top and bottom may be cut
# on some screens; read through a search on 2026-11-27 (the help page itself refused an
# unauthenticated request). The avatar's place and the 60 px bands are this script's assumption,
# drawn on crop-check.png, and are checked only once the maintainer uploads the header.
HEADER_SIZE = (1500, 500)
SAFE_BAND = 60  # top and bottom: may be cropped
AVATAR_ZONE = (0, 280, 460, 500)  # x0, y0, x1, y1: the avatar circle and its ring on a profile page

SAMPLES = {
    "en": {
        "lang": "en",
        "kicker": "Announcement",
        "title": "Your web.\nYour rules.",
        "body": "The Linux browser that is protected from the start.",
        "footer": "nulavio.net/en",
    },
    "pt-BR": {
        "lang": "pt-BR",
        "kicker": "Anúncio",
        "title": "A web é sua.\nSeus dados também.",
        "body": "O navegador para Linux que já vem protegido.",
        "footer": "nulavio.net",
    },
}
TAGLINE = {"en": "The Linux browser that is protected from the start.", "pt-BR": "O navegador para Linux que já vem protegido."}

# Average advance of Noto Sans, in em, used to wrap lines (an estimate: a line is kept a little
# shorter than the width it is given).
ADVANCE = {"bold": 0.60, "regular": 0.54}


def svg(width: int, height: int, body: str, *, title: str) -> str:
    return (
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {width} {height}" width="{width}" height="{height}" '
        f'role="img" aria-labelledby="t">\n{HEADER}\n<title id="t">{html.escape(title)}</title>\n{body}\n</svg>\n'
    )


def background(width: int, height: int, gid: str = "glow") -> str:
    """Canvas navy with a mint glow from the bottom right, as the link-preview image."""
    return (
        f'<defs><radialGradient id="{gid}" cx="{width * 0.88:.0f}" cy="{height:.0f}" r="{max(width, height) * 0.75:.0f}" '
        f'gradientUnits="userSpaceOnUse"><stop offset="0" stop-color="{GLOW}"/>'
        f'<stop offset="0.7" stop-color="{GLOW}" stop-opacity="0"/></radialGradient></defs>\n'
        f'<rect width="{width}" height="{height}" fill="{CANVAS}"/>\n'
        f'<rect width="{width}" height="{height}" fill="url(#{gid})"/>'
    )


def name(x: float, y: float, width: float) -> str:
    """The lockup on dark ("N" + "ulavio"), `width` px wide, its viewBox's top left at (x, y)."""
    view_box, body = bl.initial_lockup_parts(bl.MINT, bl.CLOUD)
    vx, vy, vw, _vh = (float(v) for v in view_box.split())
    scale = width / vw
    return f'<g transform="translate({bl.n(x)} {bl.n(y)}) scale({bl.n(scale)}) translate({bl.n(-vx)} {bl.n(-vy)})">{body}</g>'


def name_height(width: float) -> float:
    view_box, _ = bl.initial_lockup_parts(bl.MINT, bl.CLOUD)
    _vx, _vy, vw, vh = (float(v) for v in view_box.split())
    return width * vh / vw


def trail(x: float, y: float, size: float) -> str:
    """The three points, growing towards the text (the link-preview image's footer)."""
    out, cx = [], x
    for r, opacity in ((size * 0.25, 0.4), (size * 0.375, 0.7), (size * 0.5, 1.0)):
        cx += r
        out.append(f'<circle cx="{bl.n(cx)}" cy="{bl.n(y)}" r="{bl.n(r)}" fill="{ACCENT}" fill-opacity="{opacity}"/>')
        cx += r + size * 0.55
    return "".join(out)


def wrap(text: str, size: float, width: float, weight: str) -> list[str]:
    limit = max(1, int(width / (size * ADVANCE[weight])))
    lines: list[str] = []
    for paragraph in text.split("\n"):
        line = ""
        for word in paragraph.split():
            candidate = f"{line} {word}".strip()
            if line and len(candidate) > limit:
                lines.append(line)
                line = word
            else:
                line = candidate
        lines.append(line)
    return lines


def text(lines: list[str], x: float, y: float, size: float, leading: float, fill: str, weight: int, lang: str) -> str:
    spans = "".join(
        f'<tspan x="{bl.n(x)}" y="{bl.n(y + i * size * leading)}">{html.escape(line)}</tspan>' for i, line in enumerate(lines)
    )
    return (
        f'<text xml:lang="{html.escape(lang)}" font-family="{FONT}" font-size="{bl.n(size)}" font-weight="{weight}" '
        f'fill="{fill}">{spans}</text>'
    )


def validate(post: dict) -> dict:
    keys = {"lang", "kicker", "title", "body", "footer"}
    if set(post) - keys or not {"lang", "title"} <= set(post):
        raise ValueError(f"a post has the keys {sorted(keys)}; lang and title are required")
    if not all(isinstance(v, str) for v in post.values()):
        raise ValueError("every value of a post is a string")
    return {"kicker": "", "body": "", "footer": "", **post}


def post_svg(fmt: str, post: dict) -> str:
    post = validate(post)
    width, height, margin, (top_free, bottom_free) = FORMATS[fmt]
    inner = width - 2 * margin
    # The same type sizes in every format: each is at least 1080 px on its shorter side's scale.
    title_size, body_size, kicker_size, lockup_w = 88.0, 36.0, 30.0, 240.0
    parts = [background(width, height)]
    top = margin + top_free
    parts.append(name(margin, top, lockup_w))
    bottom = height - margin - bottom_free
    footer_y = bottom - kicker_size * 0.2
    if post["footer"]:
        parts.append(trail(margin, footer_y - kicker_size * 0.35, kicker_size * 0.55))
        parts.append(text([post["footer"]], margin + kicker_size * 2.1, footer_y, kicker_size, 1.2, INK, 600, post["lang"]))
    body_lines = wrap(post["body"], body_size, inner, "regular") if post["body"] else []
    title_lines = wrap(post["title"], title_size, inner, "bold")
    block = []
    y = footer_y - (kicker_size * 2.4 if post["footer"] else 0)
    if body_lines:
        y -= (len(body_lines) - 1) * body_size * 1.3
        block.append(text(body_lines, margin, y, body_size, 1.3, MUTED, 400, post["lang"]))
        y -= body_size * 1.3 + title_size * 0.45
    y -= (len(title_lines) - 1) * title_size * 1.05
    block.append(text(title_lines, margin, y, title_size, 1.05, INK, 700, post["lang"]))
    if post["kicker"]:
        y -= title_size * 1.05
        block.append(text([post["kicker"].upper()], margin, y, kicker_size, 1.2, ACCENT, 700, post["lang"]))
    if y - title_size < top + name_height(lockup_w):
        raise ValueError(f"the text does not fit the {fmt} card: shorten the title or the body")
    parts += block
    return svg(width, height, "\n".join(parts), title=f"Nulavio: {post['title'].replace(chr(10), ' ')}")


def avatar_svg() -> str:
    """The tile's gradient full bleed (a circle crop shows no corner) and the app icon's route."""
    body = (
        '<defs><linearGradient id="bg" x1="0" y1="0" x2="1" y2="1">'
        f'<stop offset="0" stop-color="{bl.SLATE}"/><stop offset="0.62" stop-color="{bl.NAVY}"/></linearGradient></defs>\n'
        '<g transform="scale(4.16667)">\n<rect width="96" height="96" fill="url(#bg)"/>\n'
        + bl.scaled(bl.mark(bl.MINT), bl.ICON_SCALE, bl.ROUTE_CENTRE)
        + "\n</g>"
    )
    return svg(400, 400, body, title="Nulavio")


def header_svg(lang: str = "en") -> str:
    width, height = HEADER_SIZE
    x0 = AVATAR_ZONE[2] + 80  # right of the avatar's column
    lockup_w = 520
    lockup_h = name_height(lockup_w)
    y = SAFE_BAND + (height - 2 * SAFE_BAND - lockup_h - 70) / 2
    parts = [
        background(width, height),
        name(x0, y, lockup_w),
        text([TAGLINE[lang]], x0 + 4, y + lockup_h + 58, 34, 1.2, MUTED, 400, lang),
    ]
    return svg(width, height, "\n".join(parts), title="Nulavio")


def all_svgs() -> dict[str, str]:
    """Every SVG file, by path relative to OUT."""
    out = {"profile/avatar.svg": avatar_svg()}
    for lang in TAGLINE:
        out[f"profile/header-{lang}.svg"] = header_svg(lang)
    for lang, sample in SAMPLES.items():
        for fmt in FORMATS:
            out[f"posts/{fmt}-{lang}.svg"] = post_svg(fmt, sample)
    return out


def rasterise(source: Path, out: Path) -> None:
    subprocess.run(["magick", "-background", "none", "-density", "96", str(source), *STRIP, str(out)], check=True)


def crop_check(out_dir: Path, sheet: Path) -> None:
    """The avatar in a circle at 400 and 48 px on X's light and dark, and the header with the
    assumed avatar place and phone crop over it. An approximation of X's page, not a capture."""
    with tempfile.TemporaryDirectory() as tmp:
        t = Path(tmp)
        avatar = out_dir / "profile" / "avatar.png"
        header = out_dir / "profile" / "header-en.png"
        circle = t / "circle.png"
        subprocess.run(
            ["magick", "-size", "400x400", "xc:none", "-fill", "white", "-draw", "circle 200,200 200,0", circle], check=True
        )
        round400 = t / "round400.png"
        subprocess.run(["magick", avatar, circle, "-compose", "DstIn", "-composite", round400], check=True)
        round48 = t / "round48.png"
        subprocess.run(["magick", round400, "-resize", "48x48", round48], check=True)
        cx, cy, r = (AVATAR_ZONE[0] + AVATAR_ZONE[2]) // 2, AVATAR_ZONE[3] - 40, (AVATAR_ZONE[2] - AVATAR_ZONE[0]) // 2 - 50
        over = t / "header-over.png"
        subprocess.run(
            [
                "magick",
                header,
                "-fill",
                "#FFFFFF40",
                "-draw",
                f"rectangle 0,0 {HEADER_SIZE[0]},{SAFE_BAND}",
                "-draw",
                f"rectangle 0,{HEADER_SIZE[1] - SAFE_BAND} {HEADER_SIZE[0]},{HEADER_SIZE[1]}",
                "-fill",
                "#000000",
                "-stroke",
                "#FFFFFF",
                "-strokewidth",
                "8",
                "-draw",
                f"circle {cx},{cy} {cx},{cy - r}",
                over,
            ],
            check=True,
        )
        avatars = t / "avatars.png"
        subprocess.run(
            [
                "magick",
                "(",
                "-size",
                "1500x460",
                "xc:#000000",
                round400,
                "-geometry",
                "+40+30",
                "-composite",
                round48,
                "-geometry",
                "+480+206",
                "-composite",
                ")",
                "(",
                "-size",
                "1500x460",
                "xc:#FFFFFF",
                round400,
                "-geometry",
                "+40+30",
                "-composite",
                round48,
                "-geometry",
                "+480+206",
                "-composite",
                ")",
                "+append",
                "-resize",
                "1500x",
                avatars,
            ],
            check=True,
        )
        subprocess.run(
            ["magick", avatars, over, "-background", "#888888", "-splice", "0x0", "-append", *STRIP, sheet], check=True
        )


def write_all(svg_only: bool = False) -> list[Path]:
    written = []
    for rel, text_ in all_svgs().items():
        path = OUT / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text_, encoding="utf-8")
        written.append(path)
        if not svg_only:
            png = path.with_suffix(".png")
            rasterise(path, png)
            written.append(png)
    if not svg_only:
        sheet = OUT / "crop-check.png"
        crop_check(OUT, sheet)
        written.append(sheet)
    return written


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--svg-only", action="store_true", help="write the SVG files only")
    sub = parser.add_subparsers(dest="command")
    one = sub.add_parser("post", help="render one post, in every format, from a JSON file")
    one.add_argument("--text", type=Path, required=True)
    one.add_argument("--out", type=Path, required=True)
    args = parser.parse_args()
    if not args.svg_only and not shutil.which("magick"):
        parser.error("need ImageMagick 7 ('magick') with librsvg to rasterise; or pass --svg-only")
    if args.command == "post":
        post = validate(json.loads(args.text.read_text(encoding="utf-8")))
        args.out.mkdir(parents=True, exist_ok=True)
        for fmt in FORMATS:
            path = args.out / f"{fmt}-{post['lang']}.svg"
            path.write_text(post_svg(fmt, post), encoding="utf-8")
            if not args.svg_only:
                rasterise(path, path.with_suffix(".png"))
            print(path)
        return 0
    for path in write_all(args.svg_only):
        print(path.relative_to(ROOT))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
