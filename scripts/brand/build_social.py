# A language tag as BCP 47 builds the common ones: a language, then at most one script, at most one
# region, then variants, in that order (en, pt-BR, es-419, zh-Hant-TW, de-CH-1901). Extensions, private
# use and the grandfathered tags are not taken, and whether a subtag is registered is not checked. The
# tag becomes part of a file name and the xml:lang attribute, so nothing else passes.
LANG = re.compile(r"[A-Za-z]{2,3}(?:-[A-Za-z]{4})?(?:-(?:[A-Za-z]{2}|[0-9]{3}))?((?:-(?:[A-Za-z0-9]{5,8}|[0-9][A-Za-z0-9]{3}))*)")

# White space in a text. A line break is LF, and CR LF, CR and Unicode's line and paragraph separators
# are read as one. A line wraps at a space or a tab only. Every other white space is refused with the
# characters that are not measured, the no-break space excepted, which is measured.
LINE_BREAK = re.compile("\r\n|[\r\u2028\u2029]")
BREAKS = " \t\n"


def language_tag(tag: str) -> bool:
    match = LANG.fullmatch(tag)
    variants = match.group(1).lower().split("-")[1:] if match else []
    return bool(match) and len(variants) == len(set(variants))  # BCP 47: a variant is not repeated


def advance(line: str, size: float, weight: int) -> float:
    """The width of one line of Noto Sans at `size` px, from the measured advances."""
    return sum(_ADVANCE[weight][c] for c in line) * size / 1000


def svg(width: int, height: int, body: str, *, title: str, lang: str = "", desc: str = "") -> str:
    """The image. role="img" hides what is inside from assistive technology, so `title` names it and
    `desc` carries the rest of the visible text; `lang` on the root covers both."""
    language = f' xml:lang="{html.escape(lang)}"' if lang else ""
    described = ' aria-describedby="d"' if desc else ""
    description = f'<desc id="d">{html.escape(desc)}</desc>\n' if desc else ""
    return (
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {width} {height}" width="{width}" height="{height}"'
        f'{language} role="img" aria-labelledby="t"{described}>\n{HEADER}\n<title id="t">{html.escape(title)}</title>\n'
        f"{description}{body}\n</svg>\n"
    )


def glow(width: int, height: int) -> tuple[int, int, int]:
    """The glow's centre and its radius: it has faded into the canvas at 0.7 of the radius."""
    return round(width * 0.88), height, round(max(width, height) * 0.75)


def background(width: int, height: int, gid: str = "glow") -> str:
    """Canvas navy with a mint glow from the bottom right, as the link-preview image."""
    cx, cy, r = glow(width, height)
    return (
        f'<defs><radialGradient id="{gid}" cx="{cx}" cy="{cy}" r="{r}" '
        f'gradientUnits="userSpaceOnUse"><stop offset="0" stop-color="{GLOW}"/>'
        f'<stop offset="0.7" stop-color="{GLOW}" stop-opacity="0"/></radialGradient></defs>\n'
        f'<rect width="{width}" height="{height}" fill="{CANVAS}"/>\n'
        f'<rect width="{width}" height="{height}" fill="url(#{gid})"/>'
    )


def name(x: float, y: float, width: float) -> str:
    """The lockup on dark ("N" + "ulavio"), `width` px wide, its viewBox's top left at (x, y)."""
    view_box, body = bl.initial_lockup_parts(bl.MINT, bl.CLOUD)
    vx, vy, vw, _vh = (float(v) for v in view_box.split())
    scale = width / vw
    return f'<g transform="translate({bl.n(x)} {bl.n(y)}) scale({bl.n(scale)}) translate({bl.n(-vx)} {bl.n(-vy)})">{body}</g>'


def name_height(width: float) -> float:
    view_box, _ = bl.initial_lockup_parts(bl.MINT, bl.CLOUD)
    _vx, _vy, vw, vh = (float(v) for v in view_box.split())
    return width * vh / vw


def trail(x: float, y: float, size: float) -> str:
    """The three points, growing towards the text (the link-preview image's footer)."""
    out, cx = [], x
    for r, opacity in ((size * 0.25, 0.4), (size * 0.375, 0.7), (size * 0.5, 1.0)):
        cx += r
        out.append(f'<circle cx="{bl.n(cx)}" cy="{bl.n(y)}" r="{bl.n(r)}" fill="{ACCENT}" fill-opacity="{opacity}"/>')
        cx += r + size * 0.55
    return "".join(out)


def wrap(text: str, size: float, width: float, weight: int) -> list[str]:
    """`text` in lines no wider than `width`, broken at spaces and tabs: a no-break space stays inside
    its word. A word wider than the line is refused."""
    lines: list[str] = []
    for paragraph in text.split("\n"):
        line = ""
        for word in re.findall(r"[^ \t]+", paragraph):
            if advance(word, size, weight) > width:
                raise ValueError(f"{word!r} is wider than the card: break it or shorten it")
            candidate = f"{line} {word}" if line else word  # the word as written: strip() takes a no-break space
            if line and advance(candidate, size, weight) > width:
                lines.append(line)
                line = word
            else:
                line = candidate
        lines.append(line)
    return lines


def text(lines: list[str], x: float, y: float, size: float, leading: float, fill: str, weight: int) -> str:
    spans = "".join(
        f'<tspan x="{bl.n(x)}" y="{bl.n(y + i * size * leading)}">{html.escape(line).replace(NBSP, "&#160;")}</tspan>'
        for i, line in enumerate(lines)
    )
    return f'<text font-family="{FONT}" font-size="{bl.n(size)}" font-weight="{weight}" fill="{fill}">{spans}</text>'


def validate(post: object) -> dict:
    """The post with its optional texts filled in, or ValueError. Everything a post can be refused for
    without drawing it is refused here, before a file is written."""
    keys = {"lang", "kicker", "title", "body", "footer"}
    if not isinstance(post, dict):
        raise ValueError("a post is a JSON object")
    if set(post) - keys or not {"lang", "title"} <= set(post):
        raise ValueError(f"a post has the keys {sorted(keys)}; lang and title are required")
    if not all(isinstance(v, str) for v in post.values()):
        raise ValueError("every value of a post is a string")
    if not language_tag(post["lang"]):
        raise ValueError(f"lang is a language tag such as en or pt-BR, not {post['lang']!r}")
    texts = {key: LINE_BREAK.sub("\n", post[key]) for key in keys - {"lang"} if key in post}
    for key in sorted(texts):
        # Line breaks, spaces and tabs separate words and are never drawn; every other character must be
        # one whose width is known. That also keeps out what XML cannot hold (NUL, surrogates).
        # The kicker is drawn in capitals, and a capital can be outside the set when its letter is inside (ÿ, µ).
        drawn = texts[key].upper() if key == "kicker" else texts[key]
        unknown = sorted({c for c in drawn if c not in BREAKS and c not in MEASURED})
        if unknown:
            listed = ", ".join(f"U+{ord(c):04X}" for c in unknown)
            raise ValueError(f"the {key} has characters this script cannot measure ({listed}): see MEASURED")
    out = {"kicker": "", "body": "", "footer": "", **post, **texts}
    # The title and the body keep the line breaks inside them; white space around them is not a line, so
    # a body of spaces is no body. The kicker and the footer are one line each, which never wraps: a
    # no-break space in them is a space.
    out |= {key: out[key].strip() for key in ("title", "body")}
    out |= {key: " ".join(out[key].split()) for key in ("kicker", "footer")}
    if not out["title"]:
        raise ValueError("the title is empty")
    return out


def post_svg(fmt: str, post: dict) -> str:
    post = validate(post)
    width, height, margin, (top_free, bottom_free) = FORMATS[fmt]
    inner = width - 2 * margin
    # The same type sizes in every format: each is at least 1080 px on its shorter side's scale.
    title_size, body_size, kicker_size, lockup_w = 88.0, 36.0, 30.0, 240.0
    parts = [background(width, height)]
    top = margin + top_free
    parts.append(name(margin, top, lockup_w))
    bottom = height - margin - bottom_free
    footer_y = bottom - kicker_size * 0.2
    kicker, footer_x = post["kicker"].upper(), margin + kicker_size * 2.1
    # The two single lines are not wrapped: one that is too wide is refused, as a word too wide is.
    for what, line, weight, room in (("kicker", kicker, 700, inner), ("footer", post["footer"], 600, width - margin - footer_x)):
        if advance(line, kicker_size, weight) > room:
            raise ValueError(f"the {what} is wider than the {fmt} card: shorten it")
    if post["footer"]:
        parts.append(trail(margin, footer_y - kicker_size * 0.35, kicker_size * 0.55))
        parts.append(text([post["footer"]], footer_x, footer_y, kicker_size, 1.2, INK, 600))
    body_lines = wrap(post["body"], body_size, inner, 400) if post["body"] else []
    title_lines = wrap(post["title"], title_size, inner, 700)
    block = []
    y = footer_y - (kicker_size * 2.4 if post["footer"] else 0)
    if body_lines:
        y -= (len(body_lines) - 1) * body_size * 1.3
        block.append(text(body_lines, margin, y, body_size, 1.3, MUTED, 400))
        y -= body_size * 1.3 + title_size * 0.45
    y -= (len(title_lines) - 1) * title_size * 1.05
    block.append(text(title_lines, margin, y, title_size, 1.05, INK, 700))
    top_size = title_size
    if kicker:
        y -= title_size * 1.05
        top_size = kicker_size
        block.append(text([kicker], margin, y, kicker_size, 1.2, ACCENT, 700))
    # y is the topmost line's baseline: that line, at its own size, must start below the lockup.
    if y - top_size < top + name_height(lockup_w):
        raise ValueError(f"the text does not fit the {fmt} card: shorten the title or the body")
    parts += block
    # What the title does not say, in the order it is read on the card: the kicker and the body as
    # sentences, then the footer as it is written (an address).
    said = [line if line[-1] in ".!?…:" else f"{line}." for line in (post["kicker"], " ".join(post["body"].split())) if line]
    return svg(
        width,
        height,
        "\n".join(parts),
        title=f"Nulavio: {' '.join(post['title'].split())}",
        lang=post["lang"],
        desc=" ".join([*said, *([post["footer"]] if post["footer"] else [])]),
    )


def avatar_svg() -> str:
    """The tile's gradient full bleed (a circle crop shows no corner) and the app icon's route."""
    body = (
        '<defs><linearGradient id="bg" x1="0" y1="0" x2="1" y2="1">'
        f'<stop offset="0" stop-color="{bl.SLATE}"/><stop offset="0.62" stop-color="{bl.NAVY}"/></linearGradient></defs>\n'
        '<g transform="scale(4.16667)">\n<rect width="96" height="96" fill="url(#bg)"/>\n'
        + bl.scaled(bl.mark(bl.MINT), bl.ICON_SCALE, bl.ROUTE_CENTRE)
        + "\n</g>"
    )
    return svg(400, 400, body, title="Nulavio")


def header_svg(lang: str = "en") -> str:
    width, height = HEADER_SIZE
    x0 = AVATAR_ZONE[2] + 80  # right of the avatar's column
    lockup_w = 520
    lockup_h = name_height(lockup_w)
    y = SAFE_BAND + (height - 2 * SAFE_BAND - lockup_h - 70) / 2
    parts = [
        background(width, height),
        name(x0, y, lockup_w),
        text([TAGLINE[lang]], x0 + 4, y + lockup_h + 58, 34, 1.2, MUTED, 400),
    ]
    return svg(width, height, "\n".join(parts), title="Nulavio", lang=lang, desc=TAGLINE[lang])


def github_svg() -> str:
    """The repository's social preview: the name as the picture, one line that says what the project
    is, and the site's address. Nothing else is drawn: a detail of the mark set beside the name was
    read as a character after it ("Nulavio !"). The name is 740 px wide and the smallest text 36 px,
    so that both are still read when the card is shown 300 px wide; nothing leaves the margin."""
    width, height = GITHUB_SIZE
    margin, inner = GITHUB_MARGIN, GITHUB_SIZE[0] - 2 * GITHUB_MARGIN
    lockup_w, line_size, footer_size = 740.0, 52.0, 36.0
    lines = GITHUB_LINE.split("\n")
    footer_x = margin + footer_size * 2.4
    for what, line, size, weight, room in (
        *(("line", line, line_size, 400, inner) for line in lines),
        ("footer", GITHUB_FOOTER, footer_size, 600, width - margin - footer_x),
    ):
        if advance(line, size, weight) > room:
            raise ValueError(f"the {what} is wider than the GitHub card: shorten it")
    footer_y = height - margin - footer_size * 0.2
    lockup_h = name_height(lockup_w)
    # The name and its line are one block, centred in the space above the footer.
    block_h = lockup_h + line_size * 1.5 + (len(lines) - 1) * line_size * 1.36
    top = margin + (footer_y - footer_size * 2.2 - margin - block_h) / 2
    if top < margin:  # each line raises the name by half a line: a third one takes it into the margin
        raise ValueError("the GitHub card's line has too many lines: the name would leave the margin")
    line_y = top + lockup_h + line_size * 1.5
    parts = [
        background(width, height),
        name(margin, top, lockup_w),
        text(lines, margin, line_y, line_size, 1.36, MUTED, 400),
        trail(margin, footer_y - footer_size * 0.35, footer_size * 0.55),
        text([GITHUB_FOOTER], footer_x, footer_y, footer_size, 1.2, INK, 600),
    ]
    said = " ".join(lines)
    return svg(width, height, "\n".join(parts), title="Nulavio", lang="en", desc=f"{said} {GITHUB_FOOTER}")


def all_svgs() -> dict[str, str]:
    """Every SVG file, by path relative to OUT."""
    out = {"profile/avatar.svg": avatar_svg(), "github/social-preview.svg": github_svg()}
    for lang in TAGLINE:
        out[f"profile/header-{lang}.svg"] = header_svg(lang)
    for lang, sample in SAMPLES.items():
        for fmt in FORMATS:
            out[f"posts/{fmt}-{lang}.svg"] = post_svg(fmt, sample)
    return out


def rasterise(source: Path, out: Path) -> None:
    subprocess.run(["magick", "-background", "none", "-density", "96", str(source), *STRIP, str(out)], check=True)


def card_rasteriser() -> None:
    """rasterise_card dithers with a grain of half an 8-bit level. An ImageMagick that holds a channel
    in 8 bits (Q8 without HDRI) rounds that grain away before it is added, and the rings come back with
    no error: such a build is refused before anything is written. `magick -version` names the build,
    as in "ImageMagick 7.1.2-35 Q16-HDRI"."""
    version = subprocess.run(["magick", "-version"], capture_output=True, text=True, check=True).stdout
    build = re.search(r"\bQ(\d+)(-HDRI)?\b", version)
    if not build or (int(build.group(1)) < 16 and not build.group(2)):
        found = build.group(0) if build else "an unknown quantum depth"
        raise ValueError(f"ImageMagick is {found}: the GitHub card needs Q16 or an HDRI build to be dithered")


def write_card(source: Path, png: Path) -> None:
    """The GitHub card, drawn beside `png` and moved over it only when it is under GitHub's limit: a
    card that is refused leaves the one before it."""
    fresh = png.with_suffix(".new.png")
    try:
        rasterise_card(source, fresh)
        if fresh.stat().st_size >= GITHUB_MAX_BYTES:
            raise ValueError(f"{png.name} would not be under 1 MB, GitHub's limit: the one before it is kept")
        os.replace(fresh, png)
    finally:
        fresh.unlink(missing_ok=True)


def rasterise_card(source: Path, out: Path) -> None:
    """GitHub's card: a PNG without an alpha channel (a network that does not draw transparency then
    shows what was drawn, not its own background), with the glow dithered.

    The glow runs between two dark colours a few 8-bit levels apart. librsvg draws it at 8 bits, in
    steps that show as rings on a card this empty. So the background is drawn here instead, by
    ImageMagick at 16 bits from the same centre, radius and colours (glow), with a grain of half a
    level either way added before it is cut to 8 bits: each pixel then rounds up or down in
    proportion, and the rings are gone. The grain is seeded, so two runs write the same file. The
    rest of the SVG is drawn over it as it is."""
    text_ = source.read_text(encoding="utf-8")
    width, height = GITHUB_SIZE
    drawn = background(width, height)
    if text_.count(drawn) != 1:
        raise ValueError(f"{source}: the background is not the one this script draws")
    cx, cy, r = glow(width, height)
    size = f"{width}x{height}"
    with tempfile.TemporaryDirectory() as tmp:
        over = Path(tmp) / "over.svg"
        over.write_text(text_.replace(drawn, ""), encoding="utf-8")
        command = ["magick", "-size", size, "-depth", "16"]
        command += ["-define", f"gradient:center={cx},{cy}", "-define", f"gradient:radii={r * 0.7:g},{r * 0.7:g}"]
        command += [f"radial-gradient:{GLOW}-{CANVAS}"]
        command += ["(", "-size", size, "xc:gray50", "-seed", "199", "+noise", "Random", "-colorspace", "Gray", ")"]
        # Mathematics: grain / 255 + background - 0.5 / 255, the grain being 0 to 1.
        command += ["-compose", "Mathematics", "-define", f"compose:args=0,{1 / 255:.6f},1,{-0.5 / 255:.6f}", "-composite"]
        command += ["-depth", "8", "(", "-background", "none", "-density", "96", str(over), ")"]
        command += ["-compose", "Over", "-composite", "-alpha", "off", "-define", "png:color-type=2", *STRIP, str(out)]
        subprocess.run(command, check=True)


