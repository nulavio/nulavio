#!/usr/bin/env python3
"""Generate the Nulavio logo family as SVG from one geometric specification.

Selected symbol: "Vanishing Route" — an N drawn as one navigation route
(round joins, like a course plotted on a chart). The route's origin, the
bottom of the left stroke, dissolves into three shrinking points: you keep
moving forward, the trail behind you does not persist. The route exits at
the top right, towards an open horizon. The dot of the "i" in the wordmark
reuses the same point.

Outputs (docs/brand/assets/logo/ and .../icons/):
  studies/      three exploratory studies (A, B, C) for docs/brand/explorations.md
  logo/         symbol, tile, wordmarks, lockups, monochrome variants
  icons/        app icon sources incl. pixel-tuned 16/24 px masters, symbolic

Run: python3 -I scripts/brand/build_logo.py  (deterministic; tests check it)
"""

from __future__ import annotations

from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
ASSETS = ROOT / "docs" / "brand" / "assets"

NAVY = "#0B1623"
SLATE = "#183746"
MINT = "#6FE0C5"
MINT_DARK = "#0F7A68"
CLOUD = "#F1F7F5"
HEADER = "<!-- Nulavio brand asset. Generated by scripts/brand/build_logo.py. Trademark: see docs/brand/guidelines.md. -->"

# --- Symbol geometry on a 96-unit grid --------------------------------------
STROKE = 10.0
ROUTE = "M30 45 V26 L66 70 V26"  # N as one route
DOTS = ((30, 56.7, 4.2), (30, 66.3, 2.9), (30, 73.3, 1.8))  # dissolving origin (cx, cy, r)
TILE_RADIUS = 21.6  # 22.5 % of 96


def svg(view_box: str, body: str, *, title: str, width: str | None = None, height: str | None = None) -> str:
    size = f' width="{width}" height="{height}"' if width and height else ""
    return (
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="{view_box}"{size} role="img" aria-labelledby="t">\n'
        f'{HEADER}\n<title id="t">{title}</title>\n{body}\n</svg>\n'
    )


def mark(color: str, *, stroke: float = STROKE, route: str = ROUTE, dots=DOTS, extra_attrs: str = "") -> str:
    circles = "\n".join(f'  <circle cx="{cx}" cy="{cy}" r="{r}"/>' for cx, cy, r in dots)
    return (
        f'<g fill="none" stroke="{color}" stroke-width="{stroke}" stroke-linecap="round" stroke-linejoin="round"{extra_attrs}>\n'
        f'  <path d="{route}"/>\n</g>\n'
        f'<g fill="{color}"{extra_attrs}>\n{circles}\n</g>'
    )


def tile_background(size: float = 96, radius: float = TILE_RADIUS, gid: str = "bg") -> str:
    return (
        f'<defs><linearGradient id="{gid}" x1="0" y1="0" x2="1" y2="1">'
        f'<stop offset="0" stop-color="{SLATE}"/><stop offset="0.62" stop-color="{NAVY}"/></linearGradient></defs>\n'
        f'<rect width="{size}" height="{size}" rx="{radius}" fill="url(#{gid})"/>\n'
        f'<rect x="0.5" y="0.5" width="{size - 1}" height="{size - 1}" rx="{radius - 0.5}" fill="none" '
        f'stroke="{CLOUD}" stroke-opacity="0.10"/>'
    )


# --- Wordmark: monoline geometric lowercase "nulavio" -----------------------
W_STROKE = 7.0
X_TOP = 27.5  # x-height (stroke centreline)
BASE = 60.0  # baseline (stroke centreline)
ASC = 12.0  # ascender top for "l"
ARCH_R = 12.0
ROUND_R = (BASE - X_TOP) / 2


def wordmark_paths() -> tuple[str, list[tuple[float, float, float]], float]:
    """Return (path data, filled dots, advance width) for the wordmark."""
    d = []
    x = 0.0
    # n
    d.append(f"M{x} {BASE} V{X_TOP} M{x} {X_TOP + ARCH_R} A{ARCH_R} {ARCH_R} 0 0 1 {x + 2 * ARCH_R} {X_TOP + ARCH_R} V{BASE}")
    x += 2 * ARCH_R + 17
    # u
    d.append(
        f"M{x} {X_TOP} V{BASE - ARCH_R} A{ARCH_R} {ARCH_R} 0 0 0 {x + 2 * ARCH_R} {BASE - ARCH_R} M{x + 2 * ARCH_R} {X_TOP} V{BASE}"
    )
    x += 2 * ARCH_R + 17
    # l
    d.append(f"M{x} {ASC} V{BASE}")
    x += 15
    # a (single storey): bowl + stem
    cx = x + ROUND_R
    cy = (X_TOP + BASE) / 2
    d.append(
        f"M{cx - ROUND_R} {cy} A{ROUND_R} {ROUND_R} 0 1 0 {cx + ROUND_R} {cy} A{ROUND_R} {ROUND_R} 0 1 0 {cx - ROUND_R} {cy} Z"
    )
    d.append(f"M{cx + ROUND_R} {X_TOP} V{BASE}")
    x = cx + ROUND_R + 13
    # v
    d.append(f"M{x} {X_TOP} L{x + 13.5} {BASE} L{x + 27} {X_TOP}")
    x += 27 + 13
    # i (stem; its dot is the vanishing point)
    d.append(f"M{x} {X_TOP} V{BASE}")
    dots = [(x, 13.6, 4.2)]
    x += 15
    # o
    cx = x + ROUND_R
    d.append(
        f"M{cx - ROUND_R} {cy} A{ROUND_R} {ROUND_R} 0 1 0 {cx + ROUND_R} {cy} A{ROUND_R} {ROUND_R} 0 1 0 {cx - ROUND_R} {cy} Z"
    )
    x = cx + ROUND_R
    return " ".join(d), dots, x


def wordmark(color: str, dot_color: str | None = None) -> tuple[str, str]:
    path, dots, advance = wordmark_paths()
    pad = W_STROKE / 2 + 1
    view_box = f"{-pad} 4 {advance + 2 * pad} 64"
    circles = "".join(f'<circle cx="{cx}" cy="{cy}" r="{r}"/>' for cx, cy, r in dots)
    body = (
        f'<path d="{path}" fill="none" stroke="{color}" stroke-width="{W_STROKE}" stroke-linecap="round" stroke-linejoin="round"/>\n'
        f'<g fill="{dot_color or color}">{circles}</g>'
    )
    return view_box, body


def lockup(mark_color: str, text_color: str, tile: bool) -> str:
    """Symbol + wordmark. Bare symbol: wordmark baseline sits on the route's
    baseline and its x-height is ~62 % of the symbol height. Tile: the
    x-height band is centred on the tile."""
    _, wm_body = wordmark(text_color, dot_color=mark_color)
    _, _, advance = wordmark_paths()
    band_top, band_bottom = X_TOP - W_STROKE / 2, BASE + W_STROKE / 2
    if tile:
        symbol = tile_background(gid="lk") + "\n" + mark(MINT)
        sym_w, sym_h, scale, gap = 96.0, 96.0, 1.0, 26.0
        ty = 48 - (band_top + band_bottom) / 2 * scale
    else:
        # Bare route bounding box on the 96 grid: x 25..71, y 21..75.1
        symbol = f'<g transform="translate(-25 -21)">{mark(mark_color)}</g>'
        sym_w, sym_h, scale, gap = 46.0, 54.1, 0.85, 22.0
        ty = 54.0 - band_bottom * scale
    tx = sym_w + gap + (W_STROKE / 2) * scale
    width = tx + (advance + W_STROKE / 2) * scale
    body = f'<g>{symbol}</g>\n<g transform="translate({tx:.2f} {ty:.2f}) scale({scale})">{wm_body}</g>'
    return svg(f"-1 -1 {width + 2:.2f} {sym_h + 2:.2f}", body, title="Nulavio")


def write(path: Path, content: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8")


def studies() -> None:
    out = ASSETS / "logo" / "studies"
    # A — Null Course: zero ring crossed by a course line (Ø / N). Rejected: reads as a prohibition sign.
    a = tile_background(gid="a") + (
        f'\n<circle cx="48" cy="48" r="22" fill="none" stroke="{MINT}" stroke-width="{STROKE}"/>'
        f'\n<path d="M27 25 L69 71" stroke="{MINT}" stroke-width="{STROKE}" stroke-linecap="round"/>'
    )
    write(out / "study-a-null-course.svg", svg("0 0 96 96", a, title="Study A — Null Course"))
    # B — Vanishing Route (selected).
    write(
        out / "study-b-vanishing-route.svg",
        svg("0 0 96 96", tile_background(gid="b") + "\n" + mark(MINT), title="Study B — Vanishing Route"),
    )
    # C — Null Disc: an N cut out of a zero/disc. Rejected: generic letter-in-circle, weak at 16 px.
    c = tile_background(gid="c") + (
        f'\n<circle cx="48" cy="48" r="30" fill="{MINT}"/>'
        f'\n<path d="M37 62 V34 L59 62 V34" fill="none" stroke="{NAVY}" stroke-width="8" stroke-linecap="round" stroke-linejoin="round"/>'
    )
    write(out / "study-c-null-disc.svg", svg("0 0 96 96", c, title="Study C — Null Disc"))


def logo_family() -> None:
    logo = ASSETS / "logo"
    write(logo / "nulavio-symbol.svg", svg("20 16 56 64", mark(MINT), title="Nulavio symbol"))
    write(logo / "nulavio-symbol-dark-on-light.svg", svg("20 16 56 64", mark(MINT_DARK), title="Nulavio symbol"))
    write(logo / "nulavio-tile.svg", svg("0 0 96 96", tile_background() + "\n" + mark(MINT), title="Nulavio"))
    write(logo / "nulavio-mono-black.svg", svg("20 16 56 64", mark("#000000"), title="Nulavio symbol (monochrome)"))
    write(logo / "nulavio-mono-white.svg", svg("20 16 56 64", mark("#FFFFFF"), title="Nulavio symbol (monochrome)"))
    vb, body = wordmark(NAVY, dot_color=MINT_DARK)
    write(logo / "nulavio-wordmark.svg", svg(vb, body, title="nulavio"))
    vb, body = wordmark(CLOUD, dot_color=MINT)
    write(logo / "nulavio-wordmark-light.svg", svg(vb, body, title="nulavio"))
    vb, body = wordmark("#000000")
    write(logo / "nulavio-wordmark-mono-black.svg", svg(vb, body, title="nulavio"))
    write(logo / "nulavio-lockup-horizontal.svg", lockup(MINT_DARK, NAVY, tile=False))
    write(logo / "nulavio-lockup-horizontal-on-dark.svg", lockup(MINT, CLOUD, tile=False))
    write(logo / "nulavio-lockup-horizontal-tile.svg", lockup(MINT, NAVY, tile=True))


def icon_masters() -> None:
    icons = ASSETS / "icons"
    full = svg("0 0 96 96", tile_background() + "\n" + mark(MINT), title="Nulavio", width="512", height="512")
    write(icons / "hicolor" / "scalable" / "apps" / "nulavio.svg", full)
    # 24 px master: stroke thickened, single dot (three dots merge at this size).
    m24 = mark(MINT, stroke=11.5, route="M30 54 V27 L66 71 V27", dots=((30, 70.0, 5.2),))
    write(
        icons / "masters" / "nulavio-24.svg",
        svg("0 0 96 96", tile_background() + "\n" + m24, title="Nulavio", width="24", height="24"),
    )
    # 16 px master on a 16-unit grid: stems centred on pixel columns 5 and 11.
    m16 = (
        f'<rect width="16" height="16" rx="3.6" fill="{NAVY}"/>\n'
        f'<g fill="none" stroke="{MINT}" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">'
        f'<path d="M5 8.5 V4 L11 12 V4"/></g>\n<circle cx="5" cy="12" r="1.15" fill="{MINT}"/>'
    )
    write(icons / "masters" / "nulavio-16.svg", svg("0 0 16 16", m16, title="Nulavio", width="16", height="16"))
    # Symbolic (monochrome, recoloured by the desktop): KDE ColorScheme-Text + currentColor.
    sym = (
        '<style id="current-color-scheme">.ColorScheme-Text{color:#232629;}</style>\n'
        '<g class="ColorScheme-Text" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">'
        '<path d="M4 8 V3 L12 13 V3"/></g>\n'
        '<circle class="ColorScheme-Text" cx="4" cy="12" r="1.25" fill="currentColor"/>'
    )
    write(
        icons / "hicolor" / "symbolic" / "apps" / "nulavio-symbolic.svg",
        svg("0 0 16 16", sym, title="Nulavio", width="16", height="16"),
    )
    write(ASSETS / "favicon" / "favicon.svg", svg("0 0 96 96", tile_background() + "\n" + mark(MINT), title="Nulavio"))


def main() -> int:
    studies()
    logo_family()
    icon_masters()
    print(f"wrote SVG assets under {ASSETS.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
