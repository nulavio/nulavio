def magick(*args: str | Path) -> None:
    subprocess.run(["magick", *map(str, args)], check=True)


def natural_size(path: Path) -> tuple[float, float]:
    """Width and height of one of our own SVGs: its width and height attributes, else its viewBox."""
    tag = re.search(r"<svg\b[^>]*>", path.read_text(encoding="utf-8")).group(0)
    size = [re.search(rf'\s{name}="([\d.]+)"', tag) for name in ("width", "height")]
    if all(size):
        return float(size[0].group(1)), float(size[1].group(1))
    box = [float(v) for v in re.search(r'viewBox="([^"]+)"', tag).group(1).split()]
    return box[2], box[3]


class Sheet:
    """A page of labelled panels: vector backgrounds and text, with each asset rasterised by
    itself at the size it is shown (so a 16 px icon is a real 16 px render) and pasted on top."""

    def __init__(self, width: int, tmp: Path):
        self.width, self.tmp, self.y = width, tmp, 0
        self.shapes: list[str] = []
        self.layers: list[tuple[Path, int, int]] = []

    def rect(self, x, y, w, h, fill, rx=0, stroke=None) -> None:
        line = f' stroke="{stroke}"' if stroke else ""
        self.shapes.append(f'<rect x="{x}" y="{y}" width="{w}" height="{h}" rx="{rx}" fill="{fill}"{line}/>')

    def text(self, x, y, value, size=14, fill=INK, weight=400, anchor="start") -> None:
        self.shapes.append(
            f'<text x="{x}" y="{y}" font-family="{FONT}" font-size="{size}" font-weight="{weight}" '
            f'fill="{fill}" text-anchor="{anchor}">{html.escape(value)}</text>'
        )

    def heading(self, value: str, note: str = "") -> None:
        self.y += 34
        self.text(24, self.y, value, size=17, weight=700)
        if note:
            self.text(self.width - 24, self.y, note, size=12, fill=NOTE, anchor="end")
        self.y += 12

    def raster(self, source: Path, w: int, h: int | None = None, *, zoom: int = 1, mask: str | None = None) -> Path:
        out = self.tmp / f"layer-{len(list(self.tmp.glob('layer-*.png')))}.png"
        if source.suffix == ".svg":
            nw, nh = natural_size(source)
            h = h or max(1, round(w * nh / nw))
            magick("-background", "none", "-density", f"{96 * w / nw:.4f}", source, "-resize", f"{w}x{h}!", out)
        else:
            h = h or w
            magick(source, "-resize", f"{w}x{h}!", out)
        if mask == "circle":
            disc = f"circle {w / 2 - 0.5},{h / 2 - 0.5} {w / 2 - 0.5},0"
            shape = ["(", "-size", f"{w}x{h}", "xc:none", "-fill", "white", "-draw", disc, ")"]
            magick(out, "-alpha", "set", *shape, "-compose", "DstIn", "-composite", out)
        if zoom != 1:
            magick(out, "-filter", "point", "-resize", f"{zoom * 100}%", out)
        return out

    def place(self, source: Path, x: int, y: int, w: int, h: int | None = None, **kwargs) -> tuple[int, int]:
        layer = self.raster(source, w, h, **kwargs)
        self.layers.append((layer, x, y))
        size = subprocess.run(["magick", "identify", "-format", "%w %h", str(layer)], capture_output=True, check=True)
        lw, lh = map(int, size.stdout.split())
        return lw, lh

    def render(self, out: Path) -> None:
        height = self.y + 24
        base = self.tmp / "base.svg"
        base.write_text(
            f'<svg xmlns="http://www.w3.org/2000/svg" width="{self.width}" height="{height}">'
            f'<rect width="100%" height="100%" fill="{PAPER}"/>' + "".join(self.shapes) + "</svg>",
            encoding="utf-8",
        )
        cmd: list[str | Path] = [base]
        for layer, x, y in self.layers:
            cmd += [layer, "-geometry", f"+{x}+{y}", "-composite"]
        out.parent.mkdir(parents=True, exist_ok=True)
        magick(*cmd, *LOSSLESS, out)


def android_today() -> tuple[str, str]:
    """(foreground as SVG on the 108-unit canvas, background colour), read from the Companion's resources."""
    res = ROOT / "android" / "app" / "src" / "main" / "res" / "drawable"
    attributes = lambda tag: dict(re.findall(r'android:(\w+)="([^"]*)"', tag))  # noqa: E731
    text = (res / "ic_launcher_foreground.xml").read_text(encoding="utf-8")
    group = attributes(re.search(r"<group\b[^>]*>", text).group(0))
    paths = []
    for tag in re.findall(r"<path\b[^>]*/>", text):
        path = attributes(tag)
        if "strokeColor" in path:
            paths.append(
                f'<path d="{path["pathData"]}" fill="none" stroke="{path["strokeColor"]}" '
                f'stroke-width="{path["strokeWidth"]}" stroke-linecap="{path["strokeLineCap"]}" '
                f'stroke-linejoin="{path["strokeLineJoin"]}"/>'
            )
        else:
            paths.append(f'<path d="{path["pathData"]}" fill="{path["fillColor"]}"/>')
    px, py = group.get("pivotX", "0"), group.get("pivotY", "0")
    # A VectorDrawable group scales about its pivot and then translates, in viewport units.
    transform = (
        f"translate({group.get('translateX', '0')} {group.get('translateY', '0')}) translate({px} {py}) "
        f"scale({group.get('scaleX', '1')} {group.get('scaleY', '1')}) translate(-{px} -{py})"
    )
    solid = re.search(r"<solid\b[^>]*>", (res / "ic_launcher_background.xml").read_text(encoding="utf-8")).group(0)
    return f'<g transform="{transform}">{"".join(paths)}</g>', attributes(solid)["color"]


