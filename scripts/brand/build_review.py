def render() -> list[Path]:
    written = []
    with tempfile.TemporaryDirectory() as directory:
        tmp = Path(directory)
        opts = options(tmp)
        for option in opts:
            sub = tmp / option["key"]
            sub.mkdir()
            out = OUT / f"contexts-{option['key']}.webp"
            context_sheet(option, sub, out)
            written.append(out)
        others = (
            ("overview", lambda t, o: overview_sheet(opts, t, o)),
            ("palette", palette_sheet),
            ("capture-crops", captures_sheet),
            ("status-shields", shields_sheet),
        )
        for name, build in others:
            sub = tmp / name
            sub.mkdir()
            build(sub, OUT / f"{name}.webp")
            written.append(OUT / f"{name}.webp")
    return written


