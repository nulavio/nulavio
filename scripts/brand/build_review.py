# The accent's five steps today, and the same lightness and chroma turned to another hue (OKLCH).
ACCENT_STEPS = ("900", "700", "400", "200", "100")
CANDIDATE_HUES = (("Mint, as today", None), ("Leaf, 160°", 160.0), ("Aqua, 190°", 190.0), ("Cyan, 205°", 205.0))


def from_oklch(lightness: float, chroma: float, hue: float) -> str:
    a, b = chroma * math.cos(math.radians(hue)), chroma * math.sin(math.radians(hue))
    l_ = lightness + 0.3963377774 * a + 0.2158037573 * b
    m_ = lightness - 0.1055613458 * a - 0.0638541728 * b
    s_ = lightness - 0.0894841775 * a - 1.2914855480 * b
    l3, m3, s3 = l_**3, m_**3, s_**3
    linear = (
        4.0767416621 * l3 - 3.3077115913 * m3 + 0.2309699292 * s3,
        -1.2684380046 * l3 + 2.6097574011 * m3 - 0.3413193965 * s3,
        -0.0041960863 * l3 - 0.7034186147 * m3 + 1.7076147010 * s3,
    )

    def encode(value: float) -> int:
        value = min(1.0, max(0.0, value))
        return round(255 * (12.92 * value if value <= 0.0031308 else 1.055 * value ** (1 / 2.4) - 0.055))

    return "#" + "".join(f"{encode(v):02X}" for v in linear)


def oklch(color: str) -> tuple[float, float, float]:
    lightness, a, b = contrast.oklab(color)
    return lightness, math.hypot(a, b), math.degrees(math.atan2(b, a)) % 360


def accent_candidates(data: dict) -> list[dict]:
    """Each candidate accent run through every declared contrast pair, every appearance variant
    and the accent-separation rule (build_tokens.SEPARATION_MIN), by replacing the mint scale."""
    import build_tokens

    tokens = contrast.flatten(data)
    today = {step: contrast.resolve(tokens, f"color.primitive.mint.{step}") for step in ACCENT_STEPS}
    rows = []
    for name, hue in CANDIDATE_HUES:
        scale = dict(today) if hue is None else {s: from_oklch(*oklch(c)[:2], hue) for s, c in today.items()}
        changed = contrast.with_overrides(data, {f"color.primitive.mint.{s}": c for s, c in scale.items()})
        pairs = contrast.checked_pairs(changed)
        variants = contrast.variant_rows(changed)
        separation = min(contrast.accent_separation(changed), key=lambda row: row[2])
        rows.append(
            {
                "name": name,
                "scale": scale,
                "hue": oklch(scale["400"])[2],
                "on_navy": contrast.ratio(scale["400"], NAVY),
                "on_cloud": contrast.ratio(scale["700"], CLOUD),
                "pairs": len(pairs),
                "failed": sum(not row["pass"] for row in pairs),
                "variant_rows": len(variants),
                "variant_failed": sum(not row["pass"] for row in variants),
                "nearest": separation[1],
                "separation": separation[2],
                "separation_min": build_tokens.SEPARATION_MIN,
            }
        )
    return rows


def mark_report() -> list[str]:
    """The marks' own pairs as the table of docs/brand/review-2026-11.md (the test compares it line by line)."""
    lines = ["| Pair | Colours | Ratio | Needs |", "|---|---|---:|---:|"]
    for what, fg, bg, minimum in MARK_PAIRS:
        lines.append(f"| {what} | `{fg}` on `{bg}` | {contrast.ratio(fg, bg):.2f}:1 | {minimum:g}:1 |")
    return lines


def accent_report(data: dict) -> tuple[list[str], str]:
    """The accent candidates as a table, and how much was checked. It depends on every token the
    accent is kept apart from, so the document dates it instead of the test pinning it."""
    rows = accent_candidates(data)
    lines = [
        "| Accent | Dark / light value | Hue | On navy | On Cloud White | Contrast pairs failing "
        "| Nearest reserved colour (OKLab) |",
        "|---|---|---:|---:|---:|---:|---|",
    ]
    for row in rows:
        ok = "holds" if row["separation"] >= row["separation_min"] else f"**under the {row['separation_min']:g} rule**"
        nearest = row["nearest"].split(".", 2)[2]
        lines.append(
            f"| {row['name']} | `{row['scale']['400']}` / `{row['scale']['700']}` | {row['hue']:.0f}° "
            f"| {row['on_navy']:.2f}:1 | {row['on_cloud']:.2f}:1 | {row['failed'] + row['variant_failed']} "
            f"| `{nearest}` at {row['separation']:.3f}: {ok} |"
        )
    checked = f"{rows[0]['pairs']} checked pairs, {rows[0]['variant_rows']} rows across every appearance variant"
    return lines, checked


