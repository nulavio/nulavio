#!/usr/bin/env python3
"""Generate the Track B `distribution/` directory from browser/config/.

Same single source as the Track A launcher:

* distribution.ini [Preferences] -> the baseline "seed" prefs become *default*
  prefs of the Nulavio build: active from first run and still changeable by
  the user (changes are stored as user prefs). Profile-specific values
  (e.g. the generated start page) are left to the launcher.
* policies.json -> uBlock Origin installed from AMO (`normal_installed`:
  the user can disable it; Firefox verifies the Mozilla signature), allowed
  in private windows. Policies are visible to the user in about:policies.

    python3 -I scripts/build/make_distribution.py --out <install-dir>/distribution
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "launcher"))

from nulavio_launcher import __version__, extensions, prefs, profile  # noqa: E402


def distribution_ini() -> str:
    lines = [
        "; Generated by scripts/build/make_distribution.py from browser/config/prefs/baseline.js.",
        "[Global]",
        "id=nulavio",
        f"version={__version__}",
        "about=Nulavio",
        "",
        "[Preferences]",
    ]
    for pref in profile.baseline_prefs():
        if pref.mode != "seed" or (isinstance(pref.value, str) and "@" in pref.value):
            continue  # profile-specific values stay with the launcher
        lines.append(f"{pref.name}={prefs.format_value(pref.value)}")
    return "\n".join(lines) + "\n"


def policies() -> dict:
    ublock = extensions.load_lock()["ublock-origin"]
    return {
        "policies": {
            "ExtensionSettings": {
                ublock.id: {
                    "installation_mode": "normal_installed",
                    "install_url": ublock.url,
                    "private_browsing": True,
                }
            },
            "DisableTelemetry": True,
            "DisableFirefoxStudies": True,
        }
    }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--out", type=Path, required=True)
    args = parser.parse_args()
    args.out.mkdir(parents=True, exist_ok=True)
    (args.out / "distribution.ini").write_text(distribution_ini(), encoding="utf-8")
    (args.out / "policies.json").write_text(json.dumps(policies(), indent=2) + "\n", encoding="utf-8")
    print(f"wrote {args.out}/distribution.ini and policies.json")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
