#!/usr/bin/env python3
"""Assemble the Nulavio Shell built-in add-on (browser/shell/).

The Shell is a WebExtension shipped inside the Nulavio build. Firefox's own
build registers every `builtin-addons/<name>/manifest.json` packaged in
browser.jar (toolkit/mozapps/extensions/gen_built_in_addons.py), so no
Mozilla file is patched: the branding directory, which is Nulavio's, builds it
as a subdirectory.

    # assemble only (tests load it as a temporary add-on in any Firefox)
    python3 -I scripts/build/make_shell.py --out /tmp/nulavio-shell
    # make_branding.py calls install() for the Firefox source tree
"""

from __future__ import annotations

import argparse
import json
import shutil
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "browser" / "shell"
SHARED_FROM_REPO = {
    "shared/tokens.css": ROOT / "browser" / "startpage" / "tokens.css",
    "shared/base.css": ROOT / "browser" / "startpage" / "startpage.css",
    "shared/nulavio-symbol.svg": ROOT / "docs" / "brand" / "assets" / "logo" / "nulavio-symbol.svg",
    "shared/nulavio-symbol-dark-on-light.svg": ROOT / "docs" / "brand" / "assets" / "logo" / "nulavio-symbol-dark-on-light.svg",
}
JAR_DIR = "builtin-addons/nulavio-shell"
HEADER = (
    "# This Source Code Form is subject to the terms of the Mozilla Public\n"
    "# License, v. 2.0. If a copy of the MPL was not distributed with this\n"
    "# file, You can obtain one at http://mozilla.org/MPL/2.0/.\n"
    "# Generated by scripts/build/make_shell.py. Do not edit.\n"
)


def manifest() -> dict:
    return json.loads((SOURCE / "manifest.json").read_text(encoding="utf-8"))


def assemble(out: Path) -> list[str]:
    """Copy the add-on and the shared brand files into `out`; return relative file paths."""
    if out.exists():
        shutil.rmtree(out)
    shutil.copytree(SOURCE, out)
    for relative, source in SHARED_FROM_REPO.items():
        (out / relative).parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(source, out / relative)
    return sorted(str(p.relative_to(out)) for p in out.rglob("*") if p.is_file())


def write_build_files(shell_dir: Path, files: list[str]) -> None:
    lines = [HEADER, "browser.jar:"]
    lines += [f"    {JAR_DIR}/{name} ({name})" for name in files]
    (shell_dir / "jar.mn").write_text("\n".join(lines) + "\n", encoding="utf-8")
    (shell_dir / "moz.build").write_text(HEADER + '\nJAR_MANIFESTS += ["jar.mn"]\n', encoding="utf-8")


def install(branding_dir: Path) -> Path:
    """Assemble into <branding>/shell with its moz.build and jar.mn."""
    shell_dir = branding_dir / "shell"
    files = assemble(shell_dir)
    write_build_files(shell_dir, files)
    return shell_dir


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--out", type=Path, required=True, help="directory to assemble the add-on into")
    args = parser.parse_args()
    files = assemble(args.out)
    print(f"assembled {manifest()['browser_specific_settings']['gecko']['id']} ({len(files)} files) in {args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
