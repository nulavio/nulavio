#!/usr/bin/env python3
"""Assemble the Nulavio Shell built-in add-on (browser/shell/).

The Shell is a WebExtension shipped inside the Nulavio build. Firefox's own
build registers every `builtin-addons/<name>/manifest.json` packaged in
browser.jar (toolkit/mozapps/extensions/gen_built_in_addons.py), so no
Mozilla file is patched: the branding directory, which is Nulavio's, builds it
as a subdirectory.

    # assemble only; --unprivileged for a temporary add-on in a distribution Firefox
    python3 -I scripts/build/make_shell.py --out /tmp/nulavio-shell --unprivileged
    # make_branding.py calls install() for the Firefox source tree
"""

from __future__ import annotations

import argparse
import json
import shutil
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "browser" / "shell"
# Shell base/components/pages/accessibility are source-owned in shared/ and
# copied by copytree; only resources owned elsewhere are mapped here.
SHARED_FROM_REPO = {
    "shared/tokens.css": ROOT / "browser" / "startpage" / "tokens.css",
    "shared/nulavio-symbol.svg": ROOT / "docs" / "brand" / "assets" / "logo" / "nulavio-symbol.svg",
    "shared/nulavio-symbol-dark-on-light.svg": ROOT / "docs" / "brand" / "assets" / "logo" / "nulavio-symbol-dark-on-light.svg",
    # Follows the colour scheme: the toolbar, sidebar and tab icons (WCS-11).
    "shared/nulavio-symbol-adaptive.svg": ROOT / "docs" / "brand" / "assets" / "logo" / "nulavio-symbol-adaptive.svg",
    # Nulavio Connect definitions, shared with the launcher (nulavio integrations).
    "shared/integrations.json": ROOT / "browser" / "config" / "integrations.json",
}
JAR_DIR = "builtin-addons/nulavio-shell"
HEADER = (
    "# This Source Code Form is subject to the terms of the Mozilla Public\n"
    "# License, v. 2.0. If a copy of the MPL was not distributed with this\n"
    "# file, You can obtain one at http://mozilla.org/MPL/2.0/.\n"
    "# Generated by scripts/build/make_shell.py. Do not edit.\n"
)


def providers() -> dict:
    """Password providers for the Shell (flow B): browser/config/providers.json plus the pinned official
    extension of each (browser/distribution/extensions.lock.json), so the Shell installs exactly the
    version and file the launcher pins (AMO address, SHA-256)."""
    config = json.loads((ROOT / "browser" / "config" / "providers.json").read_text(encoding="utf-8"))
    pins = json.loads((ROOT / "browser" / "distribution" / "extensions.lock.json").read_text(encoding="utf-8"))
    lock = {e["key"]: e for e in pins["extensions"]}
    out = {}
    for key, provider in config["providers"].items():
        entry = lock.get(provider["extension"]) if provider.get("extension") else None
        out[key] = {
            "label": provider["label"],
            "prefs": provider["prefs"],
            "native": provider.get("native_messaging"),
            "extension": None if entry is None else {k: entry[k] for k in ("id", "name", "version", "url", "sha256", "size")},
        }
    return {"schema": 1, "generated": "scripts/build/make_shell.py", "providers": out}


def manifest() -> dict:
    return json.loads((SOURCE / "manifest.json").read_text(encoding="utf-8"))


# Parts that need the privileges of a built-in add-on (experiment APIs over
# the engine's Search Service and profile service) and the UI that uses them.
PRIVILEGED_KEYS = ("experiment_apis", "action", "commands", "omnibox", "options_ui", "sidebar_action")
PRIVILEGED_DIRS = ("experiments", "modules", "settings", "profiles", "routing", "vault", "ai", "guard", "passwords", "assistant")


def assemble(out: Path, privileged: bool = True) -> list[str]:
    """Copy the add-on and the shared brand files into `out`; return relative file paths.

    `privileged=False` builds the variant a distribution Firefox can load as a
    temporary add-on (tests on Track A): the engine rejects `experiment_apis`
    outside built-in add-ons, so those parts are left out instead of failing.
    """
    if out.exists():
        shutil.rmtree(out)
    shutil.copytree(SOURCE, out)
    for relative, source in SHARED_FROM_REPO.items():
        (out / relative).parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(source, out / relative)
    (out / "shared" / "providers.json").write_text(json.dumps(providers(), indent=2) + "\n", encoding="utf-8")
    if not privileged:
        data = json.loads((out / "manifest.json").read_text(encoding="utf-8"))
        for key in PRIVILEGED_KEYS:
            data.pop(key, None)
        (out / "manifest.json").write_text(json.dumps(data, indent=2) + "\n", encoding="utf-8")
        for name in PRIVILEGED_DIRS:
            shutil.rmtree(out / name, ignore_errors=True)
    return sorted(str(p.relative_to(out)) for p in out.rglob("*") if p.is_file())


def write_build_files(shell_dir: Path, files: list[str]) -> None:
    lines = [HEADER, "browser.jar:"]
    lines += [f"    {JAR_DIR}/{name} ({name})" for name in files]
    (shell_dir / "jar.mn").write_text("\n".join(lines) + "\n", encoding="utf-8")
    (shell_dir / "moz.build").write_text(HEADER + '\nJAR_MANIFESTS += ["jar.mn"]\n', encoding="utf-8")


def install(branding_dir: Path) -> Path:
    """Assemble into <branding>/shell with its moz.build and jar.mn."""
    shell_dir = branding_dir / "shell"
    files = assemble(shell_dir)
    write_build_files(shell_dir, files)
    return shell_dir


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--out", type=Path, required=True, help="directory to assemble the add-on into")
    parser.add_argument(
        "--unprivileged", action="store_true", help="leave out the parts that need a built-in add-on (temporary installs)"
    )
    args = parser.parse_args()
    files = assemble(args.out, privileged=not args.unprivileged)
    print(f"assembled {manifest()['browser_specific_settings']['gecko']['id']} ({len(files)} files) in {args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
