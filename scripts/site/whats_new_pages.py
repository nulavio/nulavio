def index_body(locale: str, shown: list[dict]) -> str:
    w = WORDS[locale]
    rows = "".join(
        f"""<li class="ledger-row">
<p class="state">{e(day(r["date"], locale))} · Firefox {e(r["firefox"])}</p>
<p class="item"><strong><a href="/{BASE[locale]}{e(r["version"])}/">{e(r["version"])}</a></strong>
<span>{e(r[locale]["summary"])}</span></p>
</li>
"""
        for r in shown
    )
    return f"""<section id="summary" aria-labelledby="summary-h">
<div class="summary-text">
<h1 id="summary-h">{w["index_title"]}</h1>
<p class="lead">{w["index_lead"]} <code translate="no">github.com/nulavio/nulavio/releases</code>.</p>
</div>
</section>
<section id="versions" aria-labelledby="versions-h">
<h2 id="versions-h">{w["versions"]}</h2>
<ul class="ledger">
{rows}</ul>
</section>
"""


def version_body(locale: str, r: dict) -> str:
    w, text = WORDS[locale], r[locale]
    sections = ""
    for key in ("breaking", "action", "new", "fixed"):
        items = text.get(key, [])
        if items:
            listed = "".join(f"<li>{e(item)}</li>\n" for item in items)
            sections += f"""<section id="{key}" aria-labelledby="{key}-h">
<h2 id="{key}-h">{w[key]}</h2>
<ul class="prose">
{listed}</ul>
</section>
"""
    if r.get("security"):
        ids = ", ".join(f'<code translate="no">{e(s)}</code>' for s in r["security"])
        sections += f"""<section id="security" aria-labelledby="security-h">
<h2 id="security-h">{w["security"]}</h2>
<p class="prose">{w["security_text"]} {ids}. {w["security_where"]} {ADVISORIES}.</p>
</section>
"""
    return f"""<section id="summary" aria-labelledby="summary-h">
<div class="summary-text">
<p class="pill"><strong>{e(w["channels"][r["channel"]].capitalize())}</strong> · <span class="mono">{e(r["version"])}</span></p>
<h1 id="summary-h">{e(w["title"].format(v=r["version"]))}</h1>
<p class="lead">{e(text["summary"])}</p>
<p class="prose"><a href="/{BASE[locale]}">{w["all"]}</a> · <a href="{w["download"]}">{w["get"]}</a></p>
</div>
<dl class="facts" aria-label="{w["facts"]}">
<div><dt>{w["version"]}</dt><dd class="mono">{e(r["version"])}</dd></div>
<div><dt>{w["channel"]}</dt><dd>{e(w["channels"][r["channel"]])}</dd></div>
<div><dt>{w["engine"]}</dt><dd>Firefox <span class="mono">{e(r["firefox"])}</span></dd></div>
<div><dt>{w["date"]}</dt><dd>{e(day(r["date"], locale))}</dd></div>
</dl>
</section>
{sections}"""


def pages(src: Path, released: str | None, revision_date: dict[str, str]) -> dict[str, str]:
    """{page path: HTML} for the published versions; empty when none is published. The release
    refuses a version without its record (release_notes.py), so the published one has a page."""
    shown = whats_new.published(src, released) if released else []
    if not shown:
        return {}
    out = {}
    for locale, other in (("pt-BR", "en-US"), ("en-US", "pt-BR")):
        w = WORDS[locale]
        revision = w["revision"].format(date=revision_date[locale])
        out[f"{BASE[locale]}index.html"] = page(
            locale, BASE[locale], BASE[other], w["index_title"], w["index_description"], index_body(locale, shown), revision
        )
        for r in shown:
            path, other_path = f"{BASE[locale]}{r['version']}/", f"{BASE[other]}{r['version']}/"
            title = w["title"].format(v=r["version"])
            description = w["description"].format(v=r["version"])
            out[f"{path}index.html"] = page(locale, path, other_path, title, description, version_body(locale, r), revision)
    return out
