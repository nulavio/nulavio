ADVISORIES = '<code translate="no">github.com/nulavio/nulavio/security/advisories</code>'


def e(text: str) -> str:
    return html.escape(text, quote=True)


def day(value: str, locale: str) -> str:
    date = datetime.date.fromisoformat(value)
    return date.strftime("%d/%m/%Y") if locale == "pt-BR" else date.isoformat()


